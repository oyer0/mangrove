static void exfat_replace_free(exfat_replace_transaction_t *tx)
{
    if (!tx) return;
    kfree(tx->fresh_clusters);
    kfree(tx->old_clusters);
    kfree(tx->created_state);
    if (tx->directory_growth) {
        kfree(tx->directory_growth->conversion_sectors);
        kfree(tx->directory_growth->extra);
    }
    kfree(tx->directory_growth);
    kfree(tx->retirement);
    kfree(tx->rename_destination);
    kfree(tx);
}

/* Retain the exact sector images until the write has a confirmed outcome.
 * An unsuccessful callback may already have changed persistent bytes. */
static int exfat_replace_sector_write(exfat_fs_t *fs,
                                       exfat_replace_transaction_t *tx,
                                       exfat_replace_metadata_t kind,
                                       u32 cluster, u64 sector,
                                       const u8 *before, const u8 *proposed)
{
    tx->metadata_kind = kind;
    if (kind != EXFAT_REPLACE_META_FAT) tx->metadata_partner = 0U;
    tx->metadata_cluster = cluster;
    tx->metadata_sector = sector;
    memcpy(tx->metadata_before, before, EXFAT_SECTOR_BYTES);
    memcpy(tx->metadata_proposed, proposed, EXFAT_SECTOR_BYTES);
    tx->metadata_pending = true;
    if (!exfat_write(fs, sector, 1U, proposed)) return VFS_ERR_UNCERTAIN;
    tx->metadata_pending = false;
    return VFS_OK;
}

static int exfat_replace_bitmap_update(exfat_fs_t *fs,
                                        exfat_replace_transaction_t *tx,
                                        u32 cluster, bool expected, bool used)
{
    u8 before[EXFAT_SECTOR_BYTES], proposed[EXFAT_SECTOR_BYTES];
    u64 byte = ((u64)cluster - 2ULL) / 8ULL, lba;
    u32 at = (u32)(byte % EXFAT_SECTOR_BYTES);
    u8 mask = (u8)(1U << ((cluster - 2U) % 8U));

    if (cluster < 2U || (u64)cluster >=
        (u64)fs->boot.cluster_count + 2ULL ||
        !exfat_bitmap_byte_lba(fs, byte, &lba) ||
        !exfat_read(fs, lba, 1U, before)) return VFS_ERR_IO;
    if (!!(before[at] & mask) != expected) return VFS_ERR_BAD_FORMAT;
    memcpy(proposed, before, sizeof(proposed));
    if (used) proposed[at] |= mask;
    else proposed[at] &= (u8)~mask;
    return exfat_replace_sector_write(fs, tx, EXFAT_REPLACE_META_BITMAP,
                                       cluster, lba, before, proposed);
}

/* Read every configured FAT copy before modifying any copy. Free clusters
 * may contain stale FAT values; only a link just written by this transaction
 * has an expected EOC value. A same-sector partner joins the prior fresh EOC
 * to this allocation in one write. Bitmap ownership and both ledger entries
 * already exist; complete sector images contain both affected FAT entries. */
static int exfat_replace_fat_update_pair(exfat_fs_t *fs,
                                     exfat_replace_transaction_t *tx,
                                     u32 cluster, bool check_eoc, u32 value,
                                     u32 partner)
{
    u8 before[2][EXFAT_SECTOR_BYTES], proposed[2][EXFAT_SECTOR_BYTES];
    u64 sectors[2], byte_offset;
    u32 at;

    if (cluster < 2U || (u64)cluster >=
        (u64)fs->boot.cluster_count + 2ULL ||
        !fs->boot.fat_count || fs->boot.fat_count > 2U ||
        !exfat_mul_u64(cluster, 4ULL, &byte_offset) ||
        byte_offset / EXFAT_SECTOR_BYTES >= fs->boot.fat_length ||
        (partner && (partner < 2U || partner > fs->boot.cluster_count + 1U ||
         partner == cluster || partner / 128U != cluster / 128U)))
        return VFS_ERR_BAD_FORMAT;
    at = (u32)(byte_offset % EXFAT_SECTOR_BYTES);
    for (u32 copy = 0; copy < fs->boot.fat_count; copy++) {
        sectors[copy] = (u64)fs->boot.fat_offset +
            (u64)copy * fs->boot.fat_length +
            byte_offset / EXFAT_SECTOR_BYTES;
        if (!exfat_read(fs, sectors[copy], 1U, before[copy]))
            return VFS_ERR_IO;
        if (check_eoc &&
            exfat_le32(before[copy] + at) != EXFAT_CLUSTER_EOC)
            return VFS_ERR_BAD_FORMAT;
        memcpy(proposed[copy], before[copy], EXFAT_SECTOR_BYTES);
        exfat_put32(proposed[copy] + at, value);
        if (partner) {
            u32 p = (partner % 128U) * 4U;
            if (exfat_le32(before[copy] + p) != EXFAT_CLUSTER_EOC)
                return VFS_ERR_BAD_FORMAT;
            exfat_put32(proposed[copy] + p, cluster);
        }
        tx->fat_sectors[copy] = sectors[copy];
        memcpy(tx->fat_before[copy], before[copy], EXFAT_SECTOR_BYTES);
        memcpy(tx->fat_proposed[copy], proposed[copy], EXFAT_SECTOR_BYTES);
    }
    tx->fat_copy_progress = 0;
    tx->metadata_partner = partner;
    for (u32 copy = 0; copy < fs->boot.fat_count; copy++) {
        int result = exfat_replace_sector_write(fs, tx,
            EXFAT_REPLACE_META_FAT, cluster, sectors[copy],
            before[copy], proposed[copy]);
        if (result != VFS_OK) return result;
        tx->fat_copy_progress = copy + 1U;
    }
    return VFS_OK;
}

static int exfat_replace_fat_update(exfat_fs_t *fs,
    exfat_replace_transaction_t *tx, u32 cluster, bool check_eoc, u32 value)
{
    return exfat_replace_fat_update_pair(fs, tx, cluster, check_eoc, value, 0U);
}

static int exfat_replace_old_inventory(exfat_fs_t *fs,
                                        const exfat_node_t *node,
                                        exfat_replace_transaction_t *tx,
                                        u32 limit)
{
    exfat_read_view_t fat = {0};
    u64 needed = node->data_length / fs->cluster_bytes +
                 (node->data_length % fs->cluster_bytes != 0ULL);
    u32 count = 0, current = node->first_cluster;

    if (!needed) return current ? VFS_ERR_BAD_FORMAT : VFS_OK;
    if (!limit || needed > limit || current < 2U)
        return VFS_ERR_NO_SPACE;
    tx->old_first = current;
    if (node->no_fat_chain) {
        if ((u64)current >= (u64)fs->boot.cluster_count + 2ULL ||
            needed > (u64)fs->boot.cluster_count + 2ULL - current)
            return VFS_ERR_BAD_FORMAT;
        /* A validated contiguous mapping needs a range, not one heap entry
         * per cluster. Keep this original mode independent of node updates. */
        tx->old_count = (u32)needed;
        tx->old_no_fat = true;
        return VFS_OK;
    } else {
        for (;;) {
            u32 next;
            if (count == limit) return VFS_ERR_NO_SPACE;
            if (current < 2U || (u64)current >=
                (u64)fs->boot.cluster_count + 2ULL)
                return VFS_ERR_BAD_FORMAT;
            if (!exfat_fat_get_view(fs, current, &next, &fat)) return VFS_ERR_IO;
            count++;
            if (next >= EXFAT_CLUSTER_EOC_MIN) break;
            current = next;
        }
        if (count != needed) return VFS_ERR_BAD_FORMAT;
    }
    tx->old_clusters = (u32 *)kmalloc((usize)count * sizeof(u32));
    if (!tx->old_clusters) return VFS_ERR_NO_MEM;
    tx->old_count = count;
    current = node->first_cluster;
    for (u32 i = 0; i < count; i++) {
        tx->old_clusters[i] = current;
        if (i + 1U < count && !exfat_fat_get_view(fs, current, &current, &fat))
            return VFS_ERR_IO;
    }
    return VFS_OK;
}

static u32 exfat_replace_old_cluster(const exfat_replace_transaction_t *tx,
                                      u32 index)
{
    return tx->old_no_fat ? tx->old_first + index : tx->old_clusters[index];
}

static int exfat_replace_dirty(exfat_fs_t *fs,
                                exfat_replace_transaction_t *tx)
{
    u16 flags = fs->boot.volume_flags | 0x0002U;
    if (flags == fs->boot.volume_flags) return VFS_OK;
    tx->phase = EXFAT_REPLACE_DIRTYING;
    for (u32 copy = 0; copy < 2U; copy++) {
        u64 sector = copy ? EXFAT_BACKUP_BOOT_LBA : EXFAT_MAIN_BOOT_LBA;
        if (!exfat_read(fs, sector, 1U, tx->boot_before[copy]))
            return VFS_ERR_IO;
        if (exfat_le16(tx->boot_before[copy] + 106U) !=
            fs->boot.volume_flags) return VFS_ERR_BAD_FORMAT;
        memcpy(tx->boot_proposed[copy], tx->boot_before[copy],
               EXFAT_SECTOR_BYTES);
        exfat_put16(tx->boot_proposed[copy] + 106U, flags);
    }
    for (u32 copy = 0; copy < 2U; copy++) {
        u64 sector = copy ? EXFAT_BACKUP_BOOT_LBA : EXFAT_MAIN_BOOT_LBA;
        int result = exfat_replace_sector_write(fs, tx,
            EXFAT_REPLACE_META_BOOT, copy, sector,
            tx->boot_before[copy], tx->boot_proposed[copy]);
        if (result != VFS_OK) return result;
        tx->boot_progress = copy + 1U;
    }
    fs->boot.volume_flags = flags;
    return VFS_OK;
}

/* Full scan distinguishes a missing contiguous run from an unreadable
 * allocation bitmap. The ordinary allocator's bool result cannot do that. */
static int exfat_replace_find_run(exfat_fs_t *fs, u32 count, u32 *out_first)
{
    exfat_read_view_t fat = {0};
    exfat_stream_view_t bitmap = {0};
    u32 run = 0, first = 0;
    for (u32 cluster = 2U; (u64)cluster <
         (u64)fs->boot.cluster_count + 2ULL; cluster++) {
        bool used;
        if (!exfat_bitmap_bit_view(fs, cluster, &used, &fat, &bitmap)) return VFS_ERR_IO;
        if (used) { run = 0; continue; }
        if (!run) first = cluster;
        if (++run == count) { *out_first = first; return VFS_OK; }
    }
    return VFS_ERR_NO_SPACE;
}

static int exfat_replace_next_free(exfat_fs_t *fs, u32 *io_next,
                                    u32 *out_cluster)
{
    exfat_read_view_t fat;
    exfat_stream_view_t bitmap;
    fat.valid = false;
    bitmap.mapped = bitmap.valid = false;
    for (u64 cluster = *io_next; cluster <
         (u64)fs->boot.cluster_count + 2ULL; cluster++) {
        bool used;
        if (!exfat_bitmap_bit_view(fs, (u32)cluster, &used, &fat, &bitmap)) return VFS_ERR_IO;
        if (!used) {
            *out_cluster = (u32)cluster;
            *io_next = (u32)(cluster + 1ULL);
            return VFS_OK;
        }
    }
    return VFS_ERR_NO_SPACE;
}

static int exfat_replace_stage(exfat_fs_t *fs,
                                exfat_replace_transaction_t *tx,
                                vfs_replace_source_t source, void *context)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    u32 contiguous = 0, next_free = 2U;
    int run_result;

    tx->phase = EXFAT_REPLACE_STAGING;
    if (!tx->fresh_capacity) return VFS_OK;
    run_result = exfat_replace_find_run(fs, tx->fresh_capacity, &contiguous);
    if (run_result == VFS_ERR_IO) return run_result;
    tx->new_no_fat = run_result == VFS_OK;
    for (u32 index = 0; index < tx->fresh_capacity; index++) {
        u32 candidate;
        int result;
        if (tx->new_no_fat) candidate = contiguous + index;
        else {
            result = exfat_replace_next_free(fs, &next_free, &candidate);
            if (result != VFS_OK) return result;
        }
        /* Ledger entry exists before the first write that can allocate it. */
        tx->fresh_clusters[tx->fresh_count++] = candidate;
        result = exfat_replace_bitmap_update(fs, tx, candidate, false, true);
        if (result == VFS_ERR_IO || result == VFS_ERR_BAD_FORMAT)
            tx->fresh_count--; /* No bitmap write was attempted. */
        if (result != VFS_OK) return result;
        if (!index) tx->new_first = candidate;
        if (!tx->new_no_fat) {
            u32 partner = index && tx->fresh_clusters[index - 1U] / 128U ==
                          candidate / 128U ? tx->fresh_clusters[index - 1U] : 0U;
            result = exfat_replace_fat_update_pair(fs, tx, candidate, false,
                                                  EXFAT_CLUSTER_EOC, partner);
            if (result != VFS_OK) return result;
            if (index && !partner) {
                result = exfat_replace_fat_update(fs, tx,
                    tx->fresh_clusters[index - 1U], true, candidate);
                if (result != VFS_OK) return result;
            }
        }
        u64 cluster_offset = (u64)index * fs->cluster_bytes;
        u64 lba = exfat_cluster_lba(fs, candidate);
        if (lba == ~(u64)0) return VFS_ERR_BAD_FORMAT;
        for (u32 at = 0; at < fs->sectors_per_cluster; at++) {
            u64 offset = cluster_offset + (u64)at * EXFAT_SECTOR_BYTES;
            u32 used = offset >= tx->new_length ? 0U :
                (u32)(tx->new_length - offset > EXFAT_SECTOR_BYTES ?
                      EXFAT_SECTOR_BYTES : tx->new_length - offset);
            memset(sector, 0, sizeof(sector));
            if (used && source(context, offset, sector, used) != used)
                return VFS_ERR_IO;
            if (!exfat_write(fs, lba + at, 1U, sector))
                return VFS_ERR_UNCERTAIN;
        }
    }
    return VFS_OK;
}

static int exfat_replace_cancel(exfat_fs_t *fs,
                                 exfat_replace_transaction_t *tx)
{
    tx->phase = EXFAT_REPLACE_CANCELLING;
    while (tx->cancellation_cursor < tx->fresh_count) {
        u32 cluster = tx->fresh_clusters[tx->cancellation_cursor];
        int result = exfat_replace_bitmap_update(fs, tx, cluster, true, false);
        if (result != VFS_OK) return result;
        tx->cancellation_cursor++;
    }
    if (tx->directory_growth && tx->directory_growth->appended &&
        tx->directory_growth->bitmap_written &&
        !tx->directory_growth->candidate_cancelled) {
        int result;
        if (tx->directory_growth->tail_attempted) return VFS_ERR_UNCERTAIN;
        result = exfat_replace_bitmap_update(fs, tx,
            tx->directory_growth->candidate, true, false);
        if (result != VFS_OK) return result;
        tx->directory_growth->candidate_cancelled = true;
    }
    return VFS_OK;
}

static int exfat_replace_reclaim(exfat_fs_t *fs,
                                  exfat_replace_transaction_t *tx)
{
    tx->phase = EXFAT_REPLACE_RECLAIMING;
    while (tx->reclamation_cursor < tx->old_count) {
        u32 cluster = exfat_replace_old_cluster(tx, tx->reclamation_cursor);
        int result = exfat_replace_bitmap_update(fs, tx, cluster, true, false);
        if (result != VFS_OK) return result;
        tx->reclamation_cursor++;
    }
    return VFS_OK;
}

/* Both ordinary mutations and conditional replacement publish only stream
 * allocation fields and the primary checksum. Filename entries are validated
 * by admission and remain unchanged, even when they occupy later sectors. */
static int exfat_prepare_metadata(exfat_fs_t *fs,
    const exfat_node_t *node, exfat_replace_transaction_t *tx,
    u32 first, bool no_fat, u64 valid_length, u64 data_length);
static int exfat_publish_metadata(exfat_fs_t *fs,
                                   exfat_replace_transaction_t *tx);

static bool exfat_replace_finish_handoff(vfs_super_t *sb, void *context)
{
    exfat_fs_t *fs = sb ? (exfat_fs_t *)sb->private_data : NULL;
    exfat_replace_transaction_t *tx =
        (exfat_replace_transaction_t *)context;
    if (!fs || fs->replace_transaction != tx || !tx->handoff_pending ||
        (tx->phase != EXFAT_REPLACE_HANDOFF_PUBLISHED &&
         tx->phase != EXFAT_REPLACE_HANDOFF_CANCELLED)) return false;
    fs->replace_transaction = NULL;
    fs->version_confident = true;
    exfat_replace_free(tx);
    return true;
}

/* VFS holds the retained file, offset_lock, and this mount's operation_lock.
 * The returned ACTIVE pin is finished by VFS after unlocking. */
static int exfat_replace_locked(vfs_super_t *sb, u64 record_id,
                                 u64 expected_generation, u64 length,
                                 vfs_replace_source_t source, void *context,
                                 u64 *out_pin)
{
    exfat_fs_t *fs = sb ? (exfat_fs_t *)sb->private_data : NULL;
    exfat_node_t *node = NULL;
    exfat_replace_transaction_t *tx = NULL;
    vfs_file_facts_t facts;
    int result;

    if (!fs || !out_pin || (length && !source)) return VFS_ERR_INVALID_PARAM;
    *out_pin = 0;
    if (length > MG_FILE_CONTENT_MAX_BYTES) return VFS_ERR_NO_SPACE;
    if (!fs->version_confident || fs->replace_transaction)
        return VFS_ERR_UNCERTAIN;
    if (fs->read_only) return VFS_ERR_ACCESS_DENIED;
    if (!block_device_id_is_live(fs->device_id)) return VFS_ERR_DEVICE_GONE;
    for (node = fs->nodes; node; node = node->next)
        if (node->alive && node->vfs_node &&
            node->vfs_node->inode == record_id) break;
    if (!node || node->vfs_node->type != VFS_TYPE_FILE)
        return VFS_ERR_NOT_FOUND;
    result = exfat_file_facts(node->vfs_node, &facts);
    if (result != VFS_OK) return result;
    if (node->attributes & EXFAT_ATTR_READ_ONLY)
        return VFS_ERR_ACCESS_DENIED;
    if (facts.record_id != record_id) return VFS_ERR_BAD_FORMAT;
    if (facts.generation != expected_generation)
        return VFS_ERR_STALE_GENERATION;
    if (expected_generation == ~(u64)0) return VFS_ERR_NO_SPACE;
    result = exfat_ownership_preflight_locked(node->vfs_node);
    if (result != VFS_OK) return result;
    if (!fs->cluster_bytes || !fs->sectors_per_cluster ||
        fs->cluster_bytes != fs->sectors_per_cluster * EXFAT_SECTOR_BYTES)
        return VFS_ERR_BAD_FORMAT;
    u32 count = (u32)(length / fs->cluster_bytes +
                       (length % fs->cluster_bytes != 0ULL));
    tx = (exfat_replace_transaction_t *)kmalloc(sizeof(*tx));
    if (!tx) return VFS_ERR_NO_MEM;
    memset(tx, 0, sizeof(*tx));
    tx->record_id = record_id;
    tx->expected_generation = expected_generation;
    tx->old_data_length = node->data_length;
    tx->old_valid_length = node->valid_data_length;
    tx->new_length = length;
    tx->fresh_capacity = count;
    result = exfat_replace_old_inventory(fs, node, tx,
        MG_FILE_CONTENT_MAX_BYTES / fs->cluster_bytes);
    if (result != VFS_OK) goto before_pin;
    if (count) {
        tx->fresh_clusters = (u32 *)kmalloc((usize)count * sizeof(u32));
        if (!tx->fresh_clusters) { result = VFS_ERR_NO_MEM; goto before_pin; }
    }
    result = exfat_prepare_metadata(fs, node, tx,
        node->first_cluster, node->no_fat_chain,
        node->valid_data_length, node->data_length);
    if (result != VFS_OK) goto before_pin;
    fs->replace_transaction = tx;
    result = vfs_recovery_pin_begin_handoff(sb, exfat_replace_finish_handoff,
                                            tx, &tx->pin_id);
    if (result != VFS_OK) {
        fs->replace_transaction = NULL;
        goto before_pin;
    }
    fs->version_confident = false; /* Mutation gate through pin handoff. */
    result = exfat_replace_dirty(fs, tx);
    if (result == VFS_ERR_UNCERTAIN || result == VFS_ERR_BAD_FORMAT)
        goto uncertain;
    if (result != VFS_OK) goto cancel;
    result = exfat_replace_stage(fs, tx, source, context);
    if (result == VFS_ERR_UNCERTAIN || result == VFS_ERR_BAD_FORMAT)
        goto uncertain;
    if (result != VFS_OK) goto cancel;
    tx->phase = EXFAT_REPLACE_FLUSHING;
    if (!block_flush_for_id(fs->dev, fs->device_id)) goto uncertain;
    tx->staging_flushed = true;
    /* Refresh complete sector images after staging. Never publish an image
     * captured before preceding confirmed allocation or data writes. */
    result = exfat_prepare_metadata(fs, node, tx,
        tx->new_first, tx->new_no_fat, length, length);
    if (result == VFS_ERR_BAD_FORMAT) goto uncertain;
    if (result != VFS_OK) goto cancel;
    result = exfat_publish_metadata(fs, tx);
    if (result != VFS_OK) goto uncertain;
    node->first_cluster = tx->new_first;
    node->no_fat_chain = tx->new_no_fat;
    node->data_length = length;
    node->valid_data_length = length;
    exfat_version_advance(node);
    vfs_nodes_update_size(sb, record_id, length);
    tx->phase = EXFAT_REPLACE_FLUSHING;
    if (!block_flush_for_id(fs->dev, fs->device_id)) goto uncertain;
    tx->publication_flushed = true;
    result = exfat_replace_reclaim(fs, tx);
    if (result != VFS_OK) goto uncertain;
    tx->phase = EXFAT_REPLACE_FLUSHING;
    if (!block_flush_for_id(fs->dev, fs->device_id)) goto uncertain;
    tx->phase = EXFAT_REPLACE_HANDOFF_PUBLISHED;
    tx->handoff_pending = true;
    *out_pin = tx->pin_id;
    return VFS_OK;

cancel:
    if (exfat_replace_cancel(fs, tx) != VFS_OK) goto uncertain;
    if (tx->boot_progress || tx->fresh_count) {
        tx->phase = EXFAT_REPLACE_FLUSHING;
        if (!block_flush_for_id(fs->dev, fs->device_id)) goto uncertain;
        tx->cancellation_flushed = true;
    }
    tx->phase = EXFAT_REPLACE_HANDOFF_CANCELLED;
    tx->handoff_pending = true;
    *out_pin = tx->pin_id;
    return result;
uncertain:
    (void)vfs_recovery_pin_mark_unresolved(tx->pin_id);
    return VFS_ERR_UNCERTAIN;
before_pin:
    if (result == VFS_ERR_BAD_FORMAT) fs->version_confident = false;
    exfat_replace_free(tx);
    return result;
}

/* Mutations share the mount's one pinned transaction slot. The directory
 * images are refreshed after allocation staging:
 * an earlier confirmed bitmap or FAT write must never be overwritten by an
 * image captured before that write. */
static int exfat_entry_sector(exfat_fs_t *fs,
                                        const exfat_node_t *node, u64 offset,
                                        u64 *out_lba)
{
    u32 cluster;
    u64 lba;
    u64 within = offset % fs->cluster_bytes;
    if (!exfat_chain_cluster(fs, node->parent_cluster,
                             node->parent_no_fat_chain,
                             offset / fs->cluster_bytes, &cluster) ||
        (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
        !exfat_add_u64(lba, within / EXFAT_SECTOR_BYTES, out_lba))
        return VFS_ERR_IO;
    return VFS_OK;
}

static int exfat_prepare_metadata(exfat_fs_t *fs,
    const exfat_node_t *node, exfat_replace_transaction_t *tx,
    u32 first, bool no_fat, u64 valid_length, u64 data_length)
{
    u8 *set = tx->entry_set;
    u32 primary_at = (u32)(node->entry_offset % EXFAT_SECTOR_BYTES);
    u32 stream_at = (primary_at + EXFAT_ENTRY_BYTES) % EXFAT_SECTOR_BYTES;
    int result;

    if (!node->alive || !node->version_valid ||
        node->entry_count < 3U ||
        node->entry_count > EXFAT_MAX_SECONDARY + 1U)
        return VFS_ERR_BAD_FORMAT;
    if ((fs->replace_transaction && fs->replace_transaction != tx) ||
        (!fs->version_confident && fs->replace_transaction != tx))
        return VFS_ERR_UNCERTAIN;
    /* The owning replacement has already gated the mount. Read its validated
     * entry directly without admitting unrelated reads on that gated mount. */
    if (!exfat_dir_byte_read(fs, node->parent_cluster,
            node->parent_no_fat_chain, node->entry_offset, set,
            (u32)node->entry_count * EXFAT_ENTRY_BYTES)) return VFS_ERR_IO;
    if (set[0] != EXFAT_ENTRY_FILE ||
        set[EXFAT_ENTRY_BYTES] != EXFAT_ENTRY_STREAM ||
        exfat_le16(set + 2U) !=
            exfat_entry_checksum(set, node->entry_count) ||
        exfat_le32(set + EXFAT_ENTRY_BYTES + 20U) != node->first_cluster ||
        exfat_le64(set + EXFAT_ENTRY_BYTES + 8U) !=
            node->valid_data_length ||
        exfat_le64(set + EXFAT_ENTRY_BYTES + 24U) != node->data_length)
        return VFS_ERR_BAD_FORMAT;
    result = exfat_entry_sector(fs, node, node->entry_offset,
                                          &tx->directory_sector);
    if (result != VFS_OK) return result;
    result = exfat_entry_sector(fs, node,
        node->entry_offset + EXFAT_ENTRY_BYTES, &tx->stream_sector);
    if (result != VFS_OK) return result;
    if (!exfat_read(fs, tx->directory_sector, 1U, tx->old_sector))
        return VFS_ERR_IO;
    if (tx->stream_sector == tx->directory_sector)
        memcpy(tx->old_stream_sector, tx->old_sector, EXFAT_SECTOR_BYTES);
    else if (!exfat_read(fs, tx->stream_sector, 1U,
                         tx->old_stream_sector)) return VFS_ERR_IO;
    if (memcmp(tx->old_sector + primary_at, set, EXFAT_ENTRY_BYTES) ||
        memcmp(tx->old_stream_sector + stream_at,
               set + EXFAT_ENTRY_BYTES, EXFAT_ENTRY_BYTES))
        return VFS_ERR_BAD_FORMAT;
    memcpy(tx->proposed_sector, tx->old_sector, EXFAT_SECTOR_BYTES);
    memcpy(tx->proposed_stream_sector, tx->old_stream_sector,
           EXFAT_SECTOR_BYTES);
    set[EXFAT_ENTRY_BYTES + 1U] =
        (set[EXFAT_ENTRY_BYTES + 1U] & ~EXFAT_STREAM_FLAGS) |
        EXFAT_STREAM_ALLOCATION_POSSIBLE |
        (no_fat ? EXFAT_STREAM_NO_FAT_CHAIN : 0U);
    exfat_put64(set + EXFAT_ENTRY_BYTES + 8U, valid_length);
    exfat_put32(set + EXFAT_ENTRY_BYTES + 20U, first);
    exfat_put64(set + EXFAT_ENTRY_BYTES + 24U, data_length);
    exfat_put16(set + 2U,
                (u16)exfat_entry_checksum(set, node->entry_count));
    if (tx->stream_sector == tx->directory_sector) {
        memcpy(tx->proposed_sector + stream_at,
               set + EXFAT_ENTRY_BYTES, EXFAT_ENTRY_BYTES);
    } else {
        memcpy(tx->proposed_stream_sector + stream_at,
               set + EXFAT_ENTRY_BYTES, EXFAT_ENTRY_BYTES);
    }
    memcpy(tx->proposed_sector + primary_at, set, EXFAT_ENTRY_BYTES);
    return VFS_OK;
}

static int exfat_publish_metadata(exfat_fs_t *fs,
                                            exfat_replace_transaction_t *tx)
{
    int result;
    tx->phase = EXFAT_REPLACE_PUBLISHING;
    if (tx->stream_sector != tx->directory_sector) {
        tx->stream_attempted = tx->mutation_attempted = true;
        result = exfat_replace_sector_write(fs, tx, EXFAT_REPLACE_META_NONE,
            0U, tx->stream_sector, tx->old_stream_sector,
            tx->proposed_stream_sector);
        if (result != VFS_OK) return VFS_ERR_UNCERTAIN;
        tx->stream_written = true;
    }
    tx->primary_attempted = tx->mutation_attempted = true;
    result = exfat_replace_sector_write(fs, tx, EXFAT_REPLACE_META_NONE,
        0U, tx->directory_sector, tx->old_sector, tx->proposed_sector);
    if (result != VFS_OK) return VFS_ERR_UNCERTAIN;
    tx->primary_written = true;
    tx->publication_confirmed = true;
    return VFS_OK;
}

/* The pending data sector is retained on failure. Previous sectors have a
 * confirmed count; a torn sector cannot be reported as a confirmed partial
 * write. The caller retains and quarantines the pin on any such failure. */
static int exfat_ordinary_write_bytes(exfat_fs_t *fs,
    const exfat_node_t *view, exfat_replace_transaction_t *tx,
    u64 offset, u64 length, const u8 *input)
{
    while (length) {
        u64 within = offset % fs->cluster_bytes;
        u32 cluster;
        u64 lba;
        u32 at = (u32)(within % EXFAT_SECTOR_BYTES);
        u32 amount = EXFAT_SECTOR_BYTES - at;
        if ((u64)amount > length) amount = (u32)length;
        if (!exfat_file_cluster(fs, view, offset / fs->cluster_bytes,
                                &cluster) ||
            (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
            !exfat_add_u64(lba, within / EXFAT_SECTOR_BYTES, &lba) ||
            !exfat_read(fs, lba, 1U, tx->old_data_sector))
            return VFS_ERR_IO;
        memcpy(tx->proposed_data_sector, tx->old_data_sector,
               EXFAT_SECTOR_BYTES);
        if (input) memcpy(tx->proposed_data_sector + at, input, amount);
        else memset(tx->proposed_data_sector + at, 0, amount);
        tx->data_sector = lba;
        tx->data_attempted = tx->mutation_attempted = true;
        if (!exfat_write(fs, lba, 1U, tx->proposed_data_sector))
            return VFS_ERR_UNCERTAIN;
        tx->data_attempted = false;
        tx->data_sectors_confirmed++;
        if (input) tx->confirmed_user_bytes += amount;
        if (input) input += amount;
        offset += amount;
        length -= amount;
    }
    return VFS_OK;
}

static int exfat_ordinary_plan_fresh(exfat_fs_t *fs,
    const exfat_node_t *node, exfat_replace_transaction_t *tx,
    u32 old_count, u32 new_count)
{
    u32 first = 0, next = 2U;
    int result;
    tx->new_first = node->first_cluster;
    tx->new_no_fat = node->no_fat_chain;
    tx->fresh_capacity = new_count;
    if (!new_count) return VFS_OK;
    if (new_count > EXFAT_SCAN_MAX_CLAIMS - old_count ||
        (usize)new_count > ~(usize)0 / sizeof(u32)) return VFS_ERR_NO_SPACE;
    tx->fresh_clusters = (u32 *)kmalloc((usize)new_count * sizeof(u32));
    if (!tx->fresh_clusters) return VFS_ERR_NO_MEM;
    if (old_count && node->no_fat_chain) {
        u64 adjacent = (u64)node->first_cluster + old_count;
        bool contiguous = adjacent >= 2U &&
            adjacent + new_count <= (u64)fs->boot.cluster_count + 2ULL;
        for (u32 i = 0; contiguous && i < new_count; i++) {
            bool used;
            if (!exfat_bitmap_bit(fs, (u32)adjacent + i, &used))
                return VFS_ERR_IO;
            if (used) contiguous = false;
        }
        if (contiguous) {
            for (u32 i = 0; i < new_count; i++)
                tx->fresh_clusters[i] = (u32)adjacent + i;
            return VFS_OK;
        }
        tx->new_no_fat = false;
    } else if (!old_count) {
        result = exfat_replace_find_run(fs, new_count, &first);
        if (result == VFS_ERR_IO) return result;
        if (result == VFS_OK) {
            tx->new_no_fat = true;
            tx->new_first = first;
            for (u32 i = 0; i < new_count; i++)
                tx->fresh_clusters[i] = first + i;
            return VFS_OK;
        }
        tx->new_no_fat = false;
    }
    for (u32 i = 0; i < new_count; i++) {
        result = exfat_replace_next_free(fs, &next,
                                          &tx->fresh_clusters[i]);
        if (result != VFS_OK) return result;
    }
    if (!old_count) tx->new_first = tx->fresh_clusters[0];
    return VFS_OK;
}

static int exfat_ordinary_stage_fresh(exfat_fs_t *fs,
    const exfat_node_t *node, exfat_replace_transaction_t *tx)
{
    u32 old_count = tx->old_count;
    tx->phase = EXFAT_REPLACE_STAGING;
    for (u32 i = 0; i < tx->fresh_capacity; i++) {
        u32 cluster = tx->fresh_clusters[i];
        u64 lba = exfat_cluster_lba(fs, cluster);
        int result;
        if (lba == ~(u64)0) return VFS_ERR_BAD_FORMAT;
        /* The candidate enters the retained ledger before the bitmap write. */
        tx->fresh_count = i + 1U;
        result = exfat_replace_bitmap_update(fs, tx, cluster, false, true);
        if (result == VFS_OK || tx->metadata_pending)
            tx->mutation_attempted = true;
        if (result != VFS_OK) return result;
        tx->fresh_bitmap_progress = i + 1U;
        memset(tx->proposed_data_sector, 0, EXFAT_SECTOR_BYTES);
        for (u32 sector = 0; sector < fs->sectors_per_cluster; sector++) {
            tx->data_sector = lba + sector;
            tx->data_attempted = true;
            if (!exfat_write(fs, tx->data_sector, 1U,
                             tx->proposed_data_sector))
                return VFS_ERR_UNCERTAIN;
            tx->data_attempted = false;
            tx->data_sectors_confirmed++;
        }
        tx->fresh_zero_progress = i + 1U;
    }
    if (tx->new_no_fat || !tx->fresh_capacity) return VFS_OK;
    for (u32 i = 0; i < tx->fresh_count; i++) {
        u32 value = i + 1U < tx->fresh_count ?
            tx->fresh_clusters[i + 1U] : EXFAT_CLUSTER_EOC;
        int result = exfat_replace_fat_update(fs, tx,
            tx->fresh_clusters[i], false, value);
        if (result != VFS_OK) return result;
        tx->fresh_fat_progress = i + 1U;
    }
    if (old_count && node->no_fat_chain) {
        /* Dormant FAT entries are not trusted for a NoFatChain stream. */
        for (u32 i = 0; i < old_count; i++) {
            u32 value = i + 1U < old_count ? exfat_replace_old_cluster(tx, i + 1U) :
                tx->fresh_clusters[0];
            int result = exfat_replace_fat_update(fs, tx,
                exfat_replace_old_cluster(tx, i), false, value);
            if (result != VFS_OK) return result;
            tx->old_fat_progress = i + 1U;
        }
    } else if (old_count) {
        int result = exfat_replace_fat_update(fs, tx,
            exfat_replace_old_cluster(tx, old_count - 1U), true,
            tx->fresh_clusters[0]);
        if (result != VFS_OK) return result;
        tx->old_tail_linked = true;
    }
    return VFS_OK;
}

static int exfat_ordinary_finish(exfat_fs_t *fs,
    exfat_replace_transaction_t *tx, int result, u64 *out_pin)
{
    if (result != VFS_OK && tx->mutation_attempted) {
        fs->version_confident = false;
        (void)vfs_recovery_pin_mark_unresolved(tx->pin_id);
        return VFS_ERR_UNCERTAIN;
    }
    tx->phase = result == VFS_OK ? EXFAT_REPLACE_HANDOFF_PUBLISHED :
                                   EXFAT_REPLACE_HANDOFF_CANCELLED;
    tx->handoff_pending = true;
    fs->version_confident = false; /* Keep the mutation gate through handoff. */
    *out_pin = tx->pin_id;
    return result;
}

static int exfat_ordinary_validate_node(exfat_fs_t *fs, vfs_node_t *node)
{
    exfat_node_t *state = (exfat_node_t *)node->fs_data;
    exfat_entry_info_t entry;
    bool io_error = false;
    if (!exfat_entry_set_read_checked(fs, state->parent_cluster,
            state->parent_no_fat_chain, state->entry_offset, &entry,
            &io_error)) {
        if (io_error) return VFS_ERR_IO;
        state->version_valid = false;
        fs->version_confident = false;
        return VFS_ERR_BAD_FORMAT;
    }
    if (entry.first_cluster != state->first_cluster ||
        entry.data_length != state->data_length ||
        entry.valid_data_length != state->valid_data_length ||
        !!(entry.stream_flags & EXFAT_STREAM_NO_FAT_CHAIN) !=
            state->no_fat_chain ||
        entry.attributes != state->attributes ||
        entry.entry_count != state->entry_count ||
        strcmp(entry.name, state->name) || node->size != entry.data_length) {
        state->version_valid = false;
        return VFS_ERR_UNCERTAIN;
    }
    return VFS_OK;
}

static int exfat_node_write_pinned(vfs_node_t *node, u64 offset, u64 size,
    const void *buffer, u64 *out_bytes, u64 *out_pin)
{
    /* The VFS contract permits definite partial writes, but this path reports
     * bytes only after its complete entry-set publication and final flush.
     * An in-place data sector may have changed on error, so every failure
     * after a write attempt is uncertain rather than a guessed byte count. */
    exfat_fs_t *fs;
    exfat_node_t *state;
    exfat_replace_transaction_t *tx = NULL;
    exfat_node_t view;
    u64 final_size, new_length, new_valid, needed, old_clusters;
    u32 added;
    int result;

    if (!out_bytes || !out_pin) return VFS_ERR_INVALID_PARAM;
    *out_bytes = *out_pin = 0;
    if (!node || !node->super || !node->super->private_data ||
        !node->fs_data || node->type != VFS_TYPE_FILE ||
        (size && !buffer) || offset > ~(u64)0 - size)
        return VFS_ERR_INVALID_PARAM;
    if (!size) return VFS_OK;
    fs = (exfat_fs_t *)node->super->private_data;
    state = (exfat_node_t *)node->fs_data;
    if (!fs->version_confident || fs->replace_transaction ||
        !state->alive || !state->version_valid) return VFS_ERR_UNCERTAIN;
    if (fs->read_only || (state->attributes & EXFAT_ATTR_READ_ONLY))
        return VFS_ERR_ACCESS_DENIED;
    if (!block_device_id_is_live(fs->device_id)) return VFS_ERR_DEVICE_GONE;
    if (state->generation == ~(u64)0) return VFS_ERR_NO_SPACE;
    if (!fs->cluster_bytes || !fs->sectors_per_cluster ||
        fs->cluster_bytes != fs->sectors_per_cluster * EXFAT_SECTOR_BYTES)
        return VFS_ERR_BAD_FORMAT;
    final_size = offset + size;
    new_length = final_size > state->data_length ? final_size :
                                                     state->data_length;
    new_valid = final_size > state->valid_data_length ? final_size :
                                                           state->valid_data_length;
    old_clusters = state->data_length / fs->cluster_bytes +
        (state->data_length % fs->cluster_bytes != 0ULL);
    needed = new_length / fs->cluster_bytes +
        (new_length % fs->cluster_bytes != 0ULL);
    if (needed > EXFAT_SCAN_MAX_CLAIMS || old_clusters > needed ||
        needed > fs->boot.cluster_count)
        return VFS_ERR_NO_SPACE;
    added = (u32)(needed - old_clusters);
    result = exfat_ordinary_validate_node(fs, node);
    if (result != VFS_OK) return result;
    u32 claimed = 0;
    result = exfat_ownership_preflight_locked_count(node, NULL, &claimed);
    if (result != VFS_OK) return result;
    if (added > EXFAT_SCAN_MAX_CLAIMS - claimed)
        return VFS_ERR_NO_SPACE;
    tx = (exfat_replace_transaction_t *)kmalloc(sizeof(*tx));
    if (!tx) return VFS_ERR_NO_MEM;
    memset(tx, 0, sizeof(*tx));
    tx->record_id = node->inode;
    tx->expected_generation = state->generation;
    tx->old_data_length = state->data_length;
    tx->old_valid_length = state->valid_data_length;
    tx->new_length = new_length;
    tx->old_count = (u32)old_clusters;
    tx->old_first = state->first_cluster;
    tx->old_no_fat = state->no_fat_chain;
    if (added) {
        result = exfat_replace_old_inventory(fs, state, tx,
                                              EXFAT_SCAN_MAX_CLAIMS);
        if (result != VFS_OK) goto before_pin;
    }
    result = exfat_ordinary_plan_fresh(fs, state, tx,
                                        (u32)old_clusters, added);
    if (result != VFS_OK) goto before_pin;
    fs->replace_transaction = tx;
    result = vfs_recovery_pin_begin_handoff(node->super,
        exfat_replace_finish_handoff, tx, &tx->pin_id);
    if (result != VFS_OK) {
        fs->replace_transaction = NULL;
        goto before_pin;
    }
    result = exfat_replace_dirty(fs, tx);
    if (tx->boot_progress || tx->metadata_pending)
        tx->mutation_attempted = true;
    if (result != VFS_OK) goto finish;
    if (added) {
        result = exfat_ordinary_stage_fresh(fs, state, tx);
        if (result != VFS_OK) goto finish;
    }
    view = *state;
    view.first_cluster = tx->new_first;
    view.no_fat_chain = tx->new_no_fat;
    view.data_length = new_length;
    view.valid_data_length = new_valid;
    if (state->valid_data_length < offset &&
        state->valid_data_length < state->data_length) {
        u64 zero_end = offset < state->data_length ? offset :
                                                    state->data_length;
        result = exfat_ordinary_write_bytes(fs, &view, tx,
            state->valid_data_length,
            zero_end - state->valid_data_length, NULL);
        if (result != VFS_OK) goto finish;
    }
    result = exfat_ordinary_write_bytes(fs, &view, tx, offset, size,
                                         (const u8 *)buffer);
    if (result != VFS_OK) goto finish;
    tx->phase = EXFAT_REPLACE_FLUSHING;
    if (!block_flush_for_id(fs->dev, fs->device_id)) {
        result = VFS_ERR_UNCERTAIN;
        goto finish;
    }
    if (view.first_cluster != state->first_cluster ||
        view.no_fat_chain != state->no_fat_chain ||
        new_length != state->data_length ||
        new_valid != state->valid_data_length) {
        result = exfat_prepare_metadata(fs, state, tx,
            view.first_cluster, view.no_fat_chain, new_valid, new_length);
        if (result != VFS_OK) goto finish;
        result = exfat_publish_metadata(fs, tx);
        if (result != VFS_OK) goto finish;
    } else tx->publication_confirmed = true;
    state->first_cluster = view.first_cluster;
    state->no_fat_chain = view.no_fat_chain;
    state->data_length = new_length;
    state->valid_data_length = new_valid;
    vfs_nodes_update_size(node->super, node->inode, new_length);
    exfat_version_advance(state);
    tx->phase = EXFAT_REPLACE_FLUSHING;
    if (!block_flush_for_id(fs->dev, fs->device_id))
        result = VFS_ERR_UNCERTAIN;
    else {
        *out_bytes = size;
        result = VFS_OK;
    }
finish:
    return exfat_ordinary_finish(fs, tx, result, out_pin);
before_pin:
    exfat_replace_free(tx);
    return result;
}

static bool exfat_build_file_set(const exfat_fs_t *fs, const char *name,
                                 u16 attributes, u32 first_cluster,
                                 u64 valid_length, u64 data_length,
                                 bool no_fat_chain,
                                 u8 *set, u8 *out_count)
{
    u16 units[EXFAT_MAX_NAME_UNITS];
    u16 unit_count;
    u32 name_entries;
    u32 total_entries;

    if (!fs || !name || !set || !out_count ||
        !exfat_utf8_to_utf16(name, units, &unit_count, false)) return false;
    name_entries = (unit_count + 14U) / 15U;
    total_entries = 2U + name_entries;
    if (!unit_count || name_entries == 0U ||
        total_entries > EXFAT_MAX_SECONDARY + 1U) return false;
    memset(set, 0, (usize)total_entries * EXFAT_ENTRY_BYTES);
    set[0] = EXFAT_ENTRY_FILE;
    set[1] = (u8)(total_entries - 1U);
    exfat_put16(set + 4U, attributes);
    set[EXFAT_ENTRY_BYTES] = EXFAT_ENTRY_STREAM;
    exfat_put16(set + EXFAT_ENTRY_BYTES + 1U,
                EXFAT_STREAM_ALLOCATION_POSSIBLE |
                (no_fat_chain ? EXFAT_STREAM_NO_FAT_CHAIN : 0U));
    set[EXFAT_ENTRY_BYTES + 3U] = (u8)unit_count;
    exfat_put16(set + EXFAT_ENTRY_BYTES + 4U,
                exfat_name_hash(fs, units, unit_count));
    exfat_put64(set + EXFAT_ENTRY_BYTES + 8U, valid_length);
    exfat_put32(set + EXFAT_ENTRY_BYTES + 20U, first_cluster);
    exfat_put64(set + EXFAT_ENTRY_BYTES + 24U, data_length);
    for (u32 entry = 0; entry < name_entries; entry++) {
        u8 *name_entry = set + (2U + entry) * EXFAT_ENTRY_BYTES;
        name_entry[0] = EXFAT_ENTRY_NAME;
        for (u32 index = 0; index < 15U; index++) {
            u32 unit = entry * 15U + index;
            exfat_put16(name_entry + 2U + index * 2U,
                        unit < unit_count ? units[unit] : 0U);
        }
    }
    exfat_put16(set + 2U,
                (u16)exfat_entry_checksum(set, total_entries));
    *out_count = (u8)total_entries;
    return true;
}

/* The namespace scan has already validated this directory under the mount
 * operation lock. Reuse only deleted entries before the end marker, or a
 * zeroed tail that leaves a following end marker within the old mapping. */
static int exfat_create_sector_slot(exfat_fs_t *fs,
                                     const exfat_node_t *parent,
                                     exfat_replace_transaction_t *tx)
{
    exfat_read_view_t fat = {0};
    exfat_stream_view_t stream = {0};
    u64 capacity, run_start = 0;
    u32 run = 0;
    bool at_end = false;
    u8 entry[EXFAT_ENTRY_BYTES];

    if (!exfat_directory_capacity_view(fs, parent->first_cluster,
        parent->no_fat_chain, parent->data_length, &capacity, &fat))
        return parent->no_fat_chain ? VFS_ERR_BAD_FORMAT : VFS_ERR_IO;
    if (capacity / EXFAT_ENTRY_BYTES > EXFAT_SCAN_MAX_ENTRIES)
        return VFS_ERR_BUFFER_TOO_SMALL;
    for (u64 offset = 0; offset + EXFAT_ENTRY_BYTES <= capacity;
         offset += EXFAT_ENTRY_BYTES) {
        if (!exfat_dir_byte_read_view(fs, parent->first_cluster,
                                 parent->no_fat_chain, offset,
                                 entry, sizeof(entry), &fat, &stream)) return VFS_ERR_IO;
        if (entry[0] & 0x80U) {
            if (at_end) return VFS_ERR_NO_SPACE;
            run = 0;
            continue;
        }
        if (at_end && run && offset % EXFAT_SECTOR_BYTES == 0U)
            return VFS_ERR_NO_SPACE;
        if (!run || offset % EXFAT_SECTOR_BYTES == 0U) {
            run_start = offset;
            run = 0;
        }
        if (entry[0] == EXFAT_ENTRY_END) at_end = true;
        else if (at_end) return VFS_ERR_NO_SPACE;
        run++;
        if (run != tx->created_entry_count) continue;
        u64 end = offset + EXFAT_ENTRY_BYTES;
        if (at_end) {
            if (end + EXFAT_ENTRY_BYTES > capacity) return VFS_ERR_NO_SPACE;
            if (!exfat_dir_byte_read_view(fs, parent->first_cluster,
                                     parent->no_fat_chain, end,
                                     entry, sizeof(entry), &fat, &stream)) return VFS_ERR_IO;
            if (entry[0] != EXFAT_ENTRY_END) return VFS_ERR_NO_SPACE;
        }
        u32 cluster;
        u64 within = run_start % fs->cluster_bytes;
        u64 lba;
        if (!exfat_chain_cluster(fs, parent->first_cluster,
                                 parent->no_fat_chain,
                                 run_start / fs->cluster_bytes,
                                 &cluster)) return VFS_ERR_IO;
        lba = exfat_cluster_lba(fs, cluster);
        if (lba == ~(u64)0 ||
            !exfat_add_u64(lba, within / EXFAT_SECTOR_BYTES, &lba))
            return VFS_ERR_BAD_FORMAT;
        if (!exfat_read(fs, lba, 1U, tx->old_sector)) return VFS_ERR_IO;
        tx->directory_sector = lba;
        tx->entry_offset = run_start;
        memcpy(tx->proposed_sector, tx->old_sector, EXFAT_SECTOR_BYTES);
        return VFS_OK;
    }
    return VFS_ERR_NO_SPACE;
}

static int exfat_directory_conversion_prepare(exfat_fs_t *fs,
    const exfat_node_t *parent, u32 tail, exfat_directory_growth_t *growth)
{
    u64 first = (u64)parent->first_cluster / 128ULL;
    u64 last = (u64)tail / 128ULL;
    u64 count = last - first + 1ULL;
    u64 maximum = (EXFAT_SCAN_MAX_ENTRIES * EXFAT_ENTRY_BYTES /
                    EXFAT_SECTOR_BYTES + 127U) / 128U + 1U;
    if (last < first || last >= fs->boot.fat_length || !count ||
        count > maximum || count > (usize)-1 / sizeof(exfat_conversion_sector_t))
        return VFS_ERR_BUFFER_TOO_SMALL;
    growth->conversion_sectors = kmalloc((usize)count *
                                        sizeof(exfat_conversion_sector_t));
    if (!growth->conversion_sectors) return VFS_ERR_NO_MEM;
    memset(growth->conversion_sectors, 0, (usize)count *
           sizeof(exfat_conversion_sector_t));
    growth->conversion_count = (u32)count;
    for (u32 i = 0; i < growth->conversion_count; i++)
        growth->conversion_sectors[i].lba = (u64)fs->boot.fat_offset + first + i;
    return VFS_OK;
}

/* Preparation is read-only under the namespace proof and operation lock.
 * Creation stages one sector; rename stages initialized empty capacity before
 * publishing its spanning set. Growth retires the old end marker last. */
static int exfat_create_directory_growth_prepare(exfat_fs_t *fs,
    const exfat_node_t *parent, bool root_directory,
    u32 scanned_entries, exfat_replace_transaction_t *tx)
{
    exfat_directory_growth_t *growth;
    exfat_read_view_t fat = {0};
    exfat_stream_view_t stream = {0};
    u64 capacity, marker = ~(u64)0, target, lba;
    u32 cluster, next, tail;
    u8 entry[EXFAT_ENTRY_BYTES];
    int result;

    if (!fs || !parent || !tx ||
        tx->created_entry_count > EXFAT_MAX_SECONDARY + 1U ||
        (root_directory && parent->first_cluster != fs->root_cluster) ||
        (!root_directory && parent->first_cluster == fs->root_cluster) ||
        (root_directory && parent->no_fat_chain))
        return VFS_ERR_NO_SPACE;
    if (!exfat_directory_capacity_view(fs, parent->first_cluster,
                                       parent->no_fat_chain,
                                       parent->data_length, &capacity, &fat))
        return parent->no_fat_chain ? VFS_ERR_BAD_FORMAT : VFS_ERR_IO;
    if (!root_directory &&
        (parent->data_length != capacity ||
         parent->valid_data_length != capacity)) return VFS_ERR_BAD_FORMAT;
    if (capacity / EXFAT_ENTRY_BYTES >= EXFAT_SCAN_MAX_ENTRIES)
        return VFS_ERR_BUFFER_TOO_SMALL;
    for (u64 offset = 0; offset < capacity; offset += EXFAT_ENTRY_BYTES) {
        if (!exfat_dir_byte_read_view(fs, parent->first_cluster,
            parent->no_fat_chain,
            offset, entry, sizeof(entry), &fat, &stream)) return VFS_ERR_IO;
        if (entry[0] == EXFAT_ENTRY_END) { marker = offset; break; }
    }
    if (marker == ~(u64)0) return VFS_ERR_BAD_FORMAT;
    target = (marker & ~(u64)(EXFAT_SECTOR_BYTES - 1U)) + EXFAT_SECTOR_BYTES;
    if (target > capacity || target / EXFAT_ENTRY_BYTES +
        tx->created_entry_count + 1U > EXFAT_SCAN_MAX_ENTRIES)
        return VFS_ERR_NO_SPACE;
    /* Revealing the next sector must not expose imported live entries beyond
     * an old end marker. Reject nonzero trailing bytes conservatively. */
    for (u64 offset = marker; offset < capacity; offset += EXFAT_ENTRY_BYTES) {
        if (!exfat_dir_byte_read_view(fs, parent->first_cluster,
            parent->no_fat_chain,
            offset, entry, sizeof(entry), &fat, &stream)) return VFS_ERR_IO;
        for (u32 at = 0; at < EXFAT_ENTRY_BYTES; at++)
            if (entry[at] != 0U) return VFS_ERR_UNSUPPORTED;
    }
    growth = (exfat_directory_growth_t *)kmalloc(sizeof(*growth));
    if (!growth) return VFS_ERR_NO_MEM;
    memset(growth, 0, sizeof(*growth));
    tx->directory_growth = growth;
    growth->old_capacity = capacity;
    growth->marker_at = (u32)(marker % EXFAT_SECTOR_BYTES);
    if (!exfat_chain_cluster(fs, parent->first_cluster, parent->no_fat_chain,
        marker / fs->cluster_bytes, &cluster) ||
        (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
        !exfat_add_u64(lba, (marker % fs->cluster_bytes) /
                       EXFAT_SECTOR_BYTES, &growth->marker_sector) ||
        !exfat_read(fs, growth->marker_sector, 1U, growth->marker_before))
        return VFS_ERR_IO;
    for (u32 at = growth->marker_at; at < EXFAT_SECTOR_BYTES;
         at += EXFAT_ENTRY_BYTES)
        if (growth->marker_before[at] != EXFAT_ENTRY_END)
            return VFS_ERR_UNSUPPORTED;
    memcpy(growth->marker_proposed, growth->marker_before,
           EXFAT_SECTOR_BYTES);
    for (u32 at = growth->marker_at; at < EXFAT_SECTOR_BYTES;
         at += EXFAT_ENTRY_BYTES)
        growth->marker_proposed[at] = EXFAT_ENTRY_DELETED;

    u64 needed = target + (u64)(tx->created_entry_count + 1U) *
                           EXFAT_ENTRY_BYTES;
    u32 additions = needed > capacity ?
        (u32)((needed - capacity + fs->cluster_bytes - 1U) / fs->cluster_bytes) : 0U;
    if (additions > 2U) return VFS_ERR_NO_SPACE;
    growth->appended = additions != 0U;
    if (growth->appended) {
        if (scanned_entries > EXFAT_SCAN_MAX_ENTRIES ||
            (u64)additions * fs->cluster_bytes / EXFAT_ENTRY_BYTES >
                EXFAT_SCAN_MAX_ENTRIES - scanned_entries)
            return VFS_ERR_BUFFER_TOO_SMALL;
        if (!exfat_add_u64(capacity, (u64)additions * fs->cluster_bytes,
                           &growth->new_capacity) ||
            growth->new_capacity > 256ULL * 1024ULL * 1024ULL)
            return VFS_ERR_NO_SPACE;
        if (!exfat_chain_cluster(fs, parent->first_cluster,
             parent->no_fat_chain, capacity / fs->cluster_bytes - 1U,
             &tail)) return VFS_ERR_IO;
        if (parent->no_fat_chain) {
            bool used = true;
            if ((u64)tail < (u64)fs->boot.cluster_count + 1ULL &&
                !exfat_bitmap_bit_view(fs, tail + 1U, &used, &fat, &stream))
                return VFS_ERR_IO;
            if (!used) growth->candidate = tail + 1U;
            else {
                result = exfat_replace_find_run(fs, 1U, &growth->candidate);
                if (result != VFS_OK) return result;
            }
            growth->contiguous_extension = growth->candidate == tail + 1U;
            growth->conversion = !growth->contiguous_extension;
            if (growth->conversion) {
                result = exfat_directory_conversion_prepare(fs, parent, tail, growth);
                if (result != VFS_OK) return result;
            }
        } else {
            result = exfat_replace_find_run(fs, 1U, &growth->candidate);
            if (result != VFS_OK) return result;
            if (!exfat_fat_get_view(fs, tail, &next, &fat)) return VFS_ERR_IO;
            if (next != EXFAT_CLUSTER_EOC) return VFS_ERR_BAD_FORMAT;
        }
        if (additions == 2U) {
            growth->extra = kmalloc(sizeof(*growth->extra));
            if (!growth->extra) return VFS_ERR_NO_MEM;
            memset(growth->extra, 0, sizeof(*growth->extra));
            bool used = true;
            if ((u64)growth->candidate + 1ULL <
                    (u64)fs->boot.cluster_count + 2ULL &&
                !exfat_bitmap_bit_view(fs, growth->candidate + 1U,
                                      &used, &fat, &stream)) return VFS_ERR_IO;
            if (!used) growth->extra_candidate = growth->candidate + 1U;
            else {
                for (u32 c = 2U; (u64)c < (u64)fs->boot.cluster_count + 2ULL; c++) {
                    if (c == growth->candidate) continue;
                    if (!exfat_bitmap_bit_view(fs, c, &used, &fat, &stream))
                        return VFS_ERR_IO;
                    if (!used) { growth->extra_candidate = c; break; }
                }
                if (!growth->extra_candidate) return VFS_ERR_NO_SPACE;
            }
            if (parent->no_fat_chain &&
                growth->extra_candidate != growth->candidate + 1U &&
                growth->contiguous_extension) {
                growth->contiguous_extension = false;
                growth->conversion = true;
                result = exfat_directory_conversion_prepare(fs, parent, tail, growth);
                if (result != VFS_OK) return result;
            }
            u64 extra_byte = ((u64)growth->extra_candidate - 2ULL) / 8ULL;
            if (!exfat_bitmap_byte_lba(fs, extra_byte,
                    &growth->extra->bitmap_sector) ||
                !exfat_read(fs, growth->extra->bitmap_sector, 1U,
                            growth->extra->bitmap_before)) return VFS_ERR_IO;
            if (growth->extra->bitmap_before[extra_byte % EXFAT_SECTOR_BYTES] &
                (1U << ((growth->extra_candidate - 2U) & 7U)))
                return VFS_ERR_BAD_FORMAT;
            growth->extra->fat_sector = (u64)fs->boot.fat_offset +
                                      growth->extra_candidate / 128U;
            if (!growth->contiguous_extension &&
                !exfat_read(fs, growth->extra->fat_sector, 1U,
                            growth->extra->fat_before)) return VFS_ERR_IO;
        }
        growth->tail = tail;
        growth->target_sector = exfat_cluster_lba(fs, growth->candidate);
        if (target < capacity) {
            if (!exfat_chain_cluster(fs, parent->first_cluster,
                    parent->no_fat_chain, target / fs->cluster_bytes, &cluster))
                return VFS_ERR_IO;
            growth->target_sector = exfat_cluster_lba(fs, cluster) +
                (target % fs->cluster_bytes) / EXFAT_SECTOR_BYTES;
        }
        if (growth->target_sector == ~(u64)0) return VFS_ERR_BAD_FORMAT;
        u64 byte = ((u64)growth->candidate - 2ULL) / 8ULL;
        u32 at = (u32)(byte % EXFAT_SECTOR_BYTES);
        u8 mask = (u8)(1U << ((growth->candidate - 2U) & 7U));
        if (!exfat_bitmap_byte_lba(fs, byte, &growth->bitmap_sector) ||
            !exfat_read(fs, growth->bitmap_sector, 1U,
                        growth->bitmap_before)) return VFS_ERR_IO;
        if (growth->bitmap_before[at] & mask) return VFS_ERR_BAD_FORMAT;
        memcpy(growth->bitmap_proposed, growth->bitmap_before,
               EXFAT_SECTOR_BYTES);
        growth->bitmap_proposed[at] |= mask;
        u64 fat_byte = (u64)growth->candidate * 4ULL;
        if (fat_byte / EXFAT_SECTOR_BYTES >= fs->boot.fat_length)
            return VFS_ERR_BAD_FORMAT;
        growth->candidate_fat_sector = fs->boot.fat_offset +
                                      fat_byte / EXFAT_SECTOR_BYTES;
        if (!growth->contiguous_extension) {
            if (!exfat_read(fs, growth->candidate_fat_sector, 1U,
                            growth->candidate_fat_before)) return VFS_ERR_IO;
            memcpy(growth->candidate_fat_proposed,
                   growth->candidate_fat_before, EXFAT_SECTOR_BYTES);
            exfat_put32(growth->candidate_fat_proposed +
                        fat_byte % EXFAT_SECTOR_BYTES, growth->extra_candidate ?
                            growth->extra_candidate : EXFAT_CLUSTER_EOC);
        }
        growth->tail_fat_sector = fs->boot.fat_offset +
            ((u64)tail * 4ULL) / EXFAT_SECTOR_BYTES;
    } else {
        if (!exfat_chain_cluster(fs, parent->first_cluster,
             parent->no_fat_chain,
             target / fs->cluster_bytes, &cluster) ||
            (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
            !exfat_add_u64(lba, (target % fs->cluster_bytes) /
                           EXFAT_SECTOR_BYTES, &growth->target_sector))
            return VFS_ERR_IO;
    }
    if (!exfat_read(fs, growth->target_sector, 1U,
                    growth->target_before)) return VFS_ERR_IO;
    if (!growth->appended)
        for (u32 at = 0; at < EXFAT_SECTOR_BYTES; at++)
            if (growth->target_before[at] != 0U) return VFS_ERR_UNSUPPORTED;
    memset(growth->target_proposed, 0, EXFAT_SECTOR_BYTES);
    tx->directory_sector = growth->target_sector;
    tx->entry_offset = target;
    memcpy(tx->old_sector, growth->target_before, EXFAT_SECTOR_BYTES);
    memset(tx->proposed_sector, 0, EXFAT_SECTOR_BYTES);
    if (growth->appended && !root_directory) {
        exfat_entry_info_t entry = {0};
        bool io_error = false;
        u32 primary_cluster, stream_cluster;
        u64 primary_lba, stream_lba, stream_offset;
        if (!exfat_entry_set_read_checked(fs, parent->parent_cluster,
                parent->parent_no_fat_chain, parent->entry_offset,
                &entry, &io_error))
            return io_error ? VFS_ERR_IO : VFS_ERR_BAD_FORMAT;
        if (!(entry.attributes & EXFAT_ATTR_DIRECTORY) ||
            entry.entry_count != parent->entry_count ||
            entry.first_cluster != parent->first_cluster ||
            entry.data_length != capacity ||
            entry.valid_data_length != capacity ||
            entry.attributes != parent->attributes ||
            !!(entry.stream_flags & EXFAT_STREAM_NO_FAT_CHAIN) !=
                parent->no_fat_chain ||
            strcmp(entry.name, parent->name)) return VFS_ERR_BAD_FORMAT;
        if (!exfat_node_entry_read((exfat_node_t *)parent, fs,
                growth->parent_set_before,
                sizeof(growth->parent_set_before)) ||
            !exfat_add_u64(parent->entry_offset, EXFAT_ENTRY_BYTES,
                           &stream_offset) ||
            !exfat_chain_cluster(fs, parent->parent_cluster,
                parent->parent_no_fat_chain,
                parent->entry_offset / fs->cluster_bytes,
                &primary_cluster) ||
            !exfat_chain_cluster(fs, parent->parent_cluster,
                parent->parent_no_fat_chain,
                stream_offset / fs->cluster_bytes,
                &stream_cluster)) return VFS_ERR_IO;
        primary_lba = exfat_cluster_lba(fs, primary_cluster);
        stream_lba = exfat_cluster_lba(fs, stream_cluster);
        if (primary_lba == ~(u64)0 || stream_lba == ~(u64)0 ||
            !exfat_add_u64(primary_lba,
                (parent->entry_offset % fs->cluster_bytes) /
                EXFAT_SECTOR_BYTES, &primary_lba) ||
            !exfat_add_u64(stream_lba,
                (stream_offset % fs->cluster_bytes) /
                EXFAT_SECTOR_BYTES, &stream_lba)) return VFS_ERR_BAD_FORMAT;
        growth->parent_primary_sector = primary_lba;
        growth->parent_stream_sector = stream_lba;
        growth->parent_primary_at =
            (u32)(parent->entry_offset % EXFAT_SECTOR_BYTES);
        growth->parent_stream_at = (u32)(stream_offset % EXFAT_SECTOR_BYTES);
        memcpy(growth->parent_set_proposed, growth->parent_set_before,
               sizeof(growth->parent_set_proposed));
        exfat_put64(growth->parent_set_proposed + EXFAT_ENTRY_BYTES + 8U,
                    growth->new_capacity);
        exfat_put64(growth->parent_set_proposed + EXFAT_ENTRY_BYTES + 24U,
                    growth->new_capacity);
        if (growth->conversion)
            growth->parent_set_proposed[EXFAT_ENTRY_BYTES + 1U] &=
                (u8)~EXFAT_STREAM_NO_FAT_CHAIN;
        exfat_put16(growth->parent_set_proposed + 2U,
            exfat_entry_checksum(growth->parent_set_proposed,
                                 parent->entry_count));
        growth->parent_update = true;
    }
    return VFS_OK;
}

static void exfat_create_build_sector(exfat_replace_transaction_t *tx)
{
    u8 *set = tx->entry_set;
    u32 at = (u32)(tx->entry_offset % EXFAT_SECTOR_BYTES);
    exfat_put16(set + EXFAT_ENTRY_BYTES + 1U,
                EXFAT_STREAM_ALLOCATION_POSSIBLE |
                (tx->new_no_fat ? EXFAT_STREAM_NO_FAT_CHAIN : 0U));
    exfat_put64(set + EXFAT_ENTRY_BYTES + 8U, tx->new_length);
    exfat_put32(set + EXFAT_ENTRY_BYTES + 20U, tx->new_first);
    exfat_put64(set + EXFAT_ENTRY_BYTES + 24U, tx->new_length);
    exfat_put16(set + 2U,
                (u16)exfat_entry_checksum(set, tx->created_entry_count));
    memcpy(tx->proposed_sector + at, set,
           (usize)tx->created_entry_count * EXFAT_ENTRY_BYTES);
    if (tx->directory_growth)
        memcpy(tx->directory_growth->target_proposed, tx->proposed_sector,
               EXFAT_SECTOR_BYTES);
}

static int exfat_create_directory_growth_reserve(exfat_fs_t *fs,
    exfat_replace_transaction_t *tx)
{
    exfat_directory_growth_t *growth = tx->directory_growth;
    u8 zero[EXFAT_SECTOR_BYTES] = {0};
    if (!growth || !growth->appended) return VFS_OK;
    tx->phase = EXFAT_CREATE_DIRECTORY_PREPARING;
    if (exfat_replace_sector_write(fs, tx, EXFAT_REPLACE_META_BITMAP,
        growth->candidate, growth->bitmap_sector, growth->bitmap_before,
        growth->bitmap_proposed) != VFS_OK) return VFS_ERR_UNCERTAIN;
    growth->bitmap_written = true;
    if (!growth->contiguous_extension) {
        if (exfat_replace_sector_write(fs, tx, EXFAT_REPLACE_META_FAT,
            growth->candidate, growth->candidate_fat_sector,
            growth->candidate_fat_before, growth->candidate_fat_proposed)
            != VFS_OK) return VFS_ERR_UNCERTAIN;
        growth->fat_written = true;
    }
    if (growth->extra_candidate) {
        u64 byte = ((u64)growth->extra_candidate - 2ULL) / 8ULL;
        u32 at = (u32)(byte % EXFAT_SECTOR_BYTES);
        u8 mask = (u8)(1U << ((growth->extra_candidate - 2U) & 7U));
        if (!exfat_read(fs, growth->extra->bitmap_sector, 1U,
                        growth->extra->bitmap_before)) return VFS_ERR_UNCERTAIN;
        if (growth->extra->bitmap_before[at] & mask) return VFS_ERR_UNCERTAIN;
        memcpy(growth->extra->bitmap_proposed, growth->extra->bitmap_before,
               EXFAT_SECTOR_BYTES);
        growth->extra->bitmap_proposed[at] |= mask;
        if (exfat_replace_sector_write(fs, tx, EXFAT_REPLACE_META_BITMAP,
            growth->extra_candidate, growth->extra->bitmap_sector,
            growth->extra->bitmap_before, growth->extra->bitmap_proposed) != VFS_OK)
            return VFS_ERR_UNCERTAIN;
        growth->extra->bitmap_written = true;
        if (!growth->contiguous_extension) {
            if (!exfat_read(fs, growth->extra->fat_sector, 1U,
                            growth->extra->fat_before)) return VFS_ERR_UNCERTAIN;
            memcpy(growth->extra->fat_proposed, growth->extra->fat_before,
                   EXFAT_SECTOR_BYTES);
            exfat_put32(growth->extra->fat_proposed +
                ((u64)growth->extra_candidate * 4ULL) % EXFAT_SECTOR_BYTES,
                EXFAT_CLUSTER_EOC);
            if (exfat_replace_sector_write(fs, tx, EXFAT_REPLACE_META_FAT,
                growth->extra_candidate, growth->extra->fat_sector,
                growth->extra->fat_before, growth->extra->fat_proposed) != VFS_OK)
                return VFS_ERR_UNCERTAIN;
            growth->extra->fat_written = true;
        }
    }
    for (u32 cluster_index = 0; cluster_index <
            (growth->extra_candidate ? 2U : 1U); cluster_index++) {
        u64 lba = exfat_cluster_lba(fs, cluster_index ?
            growth->extra_candidate : growth->candidate);
        for (u32 sector = 0; sector < fs->sectors_per_cluster; sector++) {
            if (!exfat_write(fs, lba + sector, 1U, zero))
                return VFS_ERR_UNCERTAIN;
            growth->initialized_sectors++;
        }
    }
    return VFS_OK;
}

/* The old contiguous mapping stays authoritative until the checksummed
 * parent entry set switches modes. Capture complete current FAT sectors only
 * after file staging, which may have changed neighboring entries in them.
 * Once any conversion write is attempted, cancellation must retain the pin:
 * failed sector writes can be torn and the old FAT entries are undefined. */
static int exfat_create_directory_convert(exfat_fs_t *fs,
    const exfat_node_t *parent, exfat_replace_transaction_t *tx)
{
    exfat_directory_growth_t *growth = tx->directory_growth;
    u64 old_count = growth->old_capacity / fs->cluster_bytes;
    u64 first_sector = (u64)parent->first_cluster / 128ULL;
    u32 candidate_link;

    if (!growth->conversion || !old_count || !growth->conversion_count ||
        parent->first_cluster < 2U ||
        (u64)parent->first_cluster + old_count - 1ULL != growth->tail ||
        (u64)growth->tail >= (u64)fs->boot.cluster_count + 2ULL ||
        !exfat_fat_get(fs, growth->candidate, &candidate_link) ||
        candidate_link != (growth->extra_candidate ?
                           growth->extra_candidate : EXFAT_CLUSTER_EOC)) return VFS_ERR_UNCERTAIN;
    tx->phase = EXFAT_CREATE_DIRECTORY_LINKING;
    for (u32 i = 0; i < growth->conversion_count; i++) {
        exfat_conversion_sector_t *sector = &growth->conversion_sectors[i];
        if (sector->lba != (u64)fs->boot.fat_offset + first_sector + i ||
            !exfat_read(fs, sector->lba, 1U, sector->before))
            return VFS_ERR_UNCERTAIN;
        memcpy(sector->proposed, sector->before, EXFAT_SECTOR_BYTES);
        u64 sector_first = (first_sector + i) * 128ULL;
        u64 begin = parent->first_cluster > sector_first ?
                    parent->first_cluster : sector_first;
        u64 end = (u64)growth->tail < sector_first + 127ULL ?
                  growth->tail : sector_first + 127ULL;
        for (u64 cluster = begin; cluster <= end; cluster++)
            exfat_put32(sector->proposed +
                (cluster - sector_first) * 4ULL,
                (u32)(cluster == growth->tail ? growth->candidate :
                      cluster + 1ULL));
    }
    for (u32 i = 0; i < growth->conversion_count; i++) {
        exfat_conversion_sector_t *sector = &growth->conversion_sectors[i];
        if (growth->tail / 128U == parent->first_cluster / 128U + i)
            growth->tail_attempted = true;
        sector->attempted = true;
        if (!exfat_write(fs, sector->lba, 1U, sector->proposed))
            return VFS_ERR_UNCERTAIN;
        sector->written = true;
        if (growth->tail / 128U == parent->first_cluster / 128U + i)
            growth->tail_written = true;
        growth->conversion_written++;
    }
    if (!block_flush_for_id(fs->dev, fs->device_id))
        return VFS_ERR_UNCERTAIN;
    growth->flush_progress = 2U;
    return VFS_OK;
}

/* A failed prepared sector write can be torn. Once the tail link is attempted,
 * the candidate may be reachable and can never enter cancellation. */
static int exfat_create_directory_growth_publish(exfat_fs_t *fs,
    const exfat_node_t *parent, exfat_replace_transaction_t *tx)
{
    exfat_directory_growth_t *growth = tx->directory_growth;
    tx->phase = EXFAT_CREATE_DIRECTORY_PREPARING;
    growth->target_attempted = true;
    if (!exfat_write(fs, growth->target_sector, 1U,
                     growth->target_proposed))
        return VFS_ERR_UNCERTAIN;
    growth->target_written = true;
    if (!block_flush_for_id(fs->dev, fs->device_id))
        return VFS_ERR_UNCERTAIN;
    growth->flush_progress = 1U;
    if (growth->appended && growth->conversion) {
        if (exfat_create_directory_convert(fs, parent, tx) != VFS_OK)
            return VFS_ERR_UNCERTAIN;
    } else if (growth->appended && !growth->contiguous_extension) {
        tx->phase = EXFAT_CREATE_DIRECTORY_LINKING;
        /* File staging may have changed this same FAT sector. Capture its
         * complete current image just before the single tail-link attempt. */
        if (!exfat_read(fs, growth->tail_fat_sector, 1U,
                        growth->tail_fat_before)) return VFS_ERR_UNCERTAIN;
        u32 candidate_link;
        if (exfat_le32(growth->tail_fat_before +
                       ((u64)growth->tail * 4ULL) % EXFAT_SECTOR_BYTES) !=
            EXFAT_CLUSTER_EOC ||
            !exfat_fat_get(fs, growth->candidate, &candidate_link) ||
            candidate_link != (growth->extra_candidate ?
                           growth->extra_candidate : EXFAT_CLUSTER_EOC))
            return VFS_ERR_UNCERTAIN;
        memcpy(growth->tail_fat_proposed, growth->tail_fat_before,
               EXFAT_SECTOR_BYTES);
        exfat_put32(growth->tail_fat_proposed +
                    ((u64)growth->tail * 4ULL) % EXFAT_SECTOR_BYTES,
                    growth->candidate);
        growth->tail_attempted = true;
        if (!exfat_write(fs, growth->tail_fat_sector, 1U,
                         growth->tail_fat_proposed))
            return VFS_ERR_UNCERTAIN;
        growth->tail_written = true;
        if (!block_flush_for_id(fs->dev, fs->device_id))
            return VFS_ERR_UNCERTAIN;
        growth->flush_progress = 2U;
    }
    if (growth->parent_update) {
        u8 current[(EXFAT_MAX_SECONDARY + 1U) * EXFAT_ENTRY_BYTES];
        u32 bytes = (u32)parent->entry_count * EXFAT_ENTRY_BYTES;
        tx->phase = EXFAT_CREATE_PARENT_UPDATING;
        /* Capture both complete sectors after file staging and the tail
         * link. Earlier FAT/bitmap writes may share sectors with one another;
         * no stale pre-staging image may be written back here. */
        if (!exfat_dir_byte_read(fs, parent->parent_cluster,
                parent->parent_no_fat_chain, parent->entry_offset,
                current, bytes) ||
            memcmp(current, growth->parent_set_before, bytes) ||
            !exfat_read(fs, growth->parent_primary_sector, 1U,
                        growth->parent_primary_before))
            return VFS_ERR_UNCERTAIN;
        memcpy(growth->parent_primary_proposed,
               growth->parent_primary_before, EXFAT_SECTOR_BYTES);
        if (growth->parent_stream_sector == growth->parent_primary_sector) {
            if (memcmp(growth->parent_primary_before +
                       growth->parent_primary_at,
                       growth->parent_set_before, EXFAT_ENTRY_BYTES * 2U))
                return VFS_ERR_UNCERTAIN;
            memcpy(growth->parent_primary_proposed +
                   growth->parent_primary_at,
                   growth->parent_set_proposed, EXFAT_ENTRY_BYTES * 2U);
        } else {
            if (!exfat_read(fs, growth->parent_stream_sector, 1U,
                            growth->parent_stream_before) ||
                memcmp(growth->parent_primary_before +
                       growth->parent_primary_at,
                       growth->parent_set_before, EXFAT_ENTRY_BYTES) ||
                memcmp(growth->parent_stream_before +
                       growth->parent_stream_at,
                       growth->parent_set_before + EXFAT_ENTRY_BYTES,
                       EXFAT_ENTRY_BYTES)) return VFS_ERR_UNCERTAIN;
            memcpy(growth->parent_stream_proposed,
                   growth->parent_stream_before, EXFAT_SECTOR_BYTES);
            memcpy(growth->parent_stream_proposed +
                   growth->parent_stream_at,
                   growth->parent_set_proposed + EXFAT_ENTRY_BYTES,
                   EXFAT_ENTRY_BYTES);
            memcpy(growth->parent_primary_proposed +
                   growth->parent_primary_at,
                   growth->parent_set_proposed, EXFAT_ENTRY_BYTES);
            growth->parent_stream_attempted = true;
            if (!exfat_write(fs, growth->parent_stream_sector, 1U,
                             growth->parent_stream_proposed))
                return VFS_ERR_UNCERTAIN;
            growth->parent_stream_written = true;
            if (!block_flush_for_id(fs->dev, fs->device_id))
                return VFS_ERR_UNCERTAIN;
            growth->flush_progress++;
        }
        growth->parent_primary_attempted = true;
        if (!exfat_write(fs, growth->parent_primary_sector, 1U,
                         growth->parent_primary_proposed))
            return VFS_ERR_UNCERTAIN;
        growth->parent_primary_written = true;
        if (!block_flush_for_id(fs->dev, fs->device_id))
            return VFS_ERR_UNCERTAIN;
        growth->flush_progress++;
    }
    tx->phase = EXFAT_CREATE_DIRECTORY_REVEALING;
    growth->marker_attempted = true;
    if (!exfat_write(fs, growth->marker_sector, 1U,
                     growth->marker_proposed))
        return VFS_ERR_UNCERTAIN;
    growth->marker_written = true;
    if (!block_flush_for_id(fs->dev, fs->device_id))
        return VFS_ERR_UNCERTAIN;
    growth->flush_progress++;
    return VFS_OK;
}

static void exfat_discard_created_node(vfs_node_t *node, vfs_super_t *sb)
{
    if (!node || !sb || !sb->private_data || !node->fs_data) return;
    exfat_fs_t *fs = (exfat_fs_t *)sb->private_data;
    exfat_node_t *state = (exfat_node_t *)node->fs_data;
    exfat_node_t **link = &fs->nodes;
    while (*link && *link != state) link = &(*link)->next;
    if (*link == state) *link = state->next;
    node->fs_data = NULL;
    kfree(state);
}

/* VFS owns the mount lock, retained parent, and preallocated return objects.
 * The prepared entry sector or relocated end-marker sector is the namespace
 * visibility boundary; no allocation or source read follows its publication. */
static int exfat_create_contents_locked(vfs_node_t *dir,
                                         vfs_node_t *prepared_node,
                                         const char *name, u64 length,
                                         vfs_replace_source_t source,
                                         void *context,
                                         vfs_file_facts_t *out_facts,
                                         u64 *out_pin)
{
    exfat_fs_t *fs;
    exfat_node_t *parent;
    exfat_entry_info_t existing;
    exfat_replace_transaction_t *tx = NULL;
    bool found;
    u32 scanned_entries;
    int result;

    if (!dir || !prepared_node || !name || !out_facts || !out_pin ||
        !dir->super || !dir->super->private_data || !dir->fs_data ||
        (length && !source)) return VFS_ERR_INVALID_PARAM;
    *out_pin = 0;
    memset(out_facts, 0, sizeof(*out_facts));
    if (length > MG_FILE_CONTENT_MAX_BYTES) return VFS_ERR_NO_SPACE;
    fs = (exfat_fs_t *)dir->super->private_data;
    parent = (exfat_node_t *)dir->fs_data;
    if (!fs->version_confident || fs->replace_transaction)
        return VFS_ERR_UNCERTAIN;
    if (fs->read_only) return VFS_ERR_ACCESS_DENIED;
    if (!block_device_id_is_live(fs->device_id)) return VFS_ERR_DEVICE_GONE;
    if (dir->type != VFS_TYPE_DIRECTORY || !parent->alive ||
        !parent->version_valid || parent->vfs_node != dir)
        return VFS_ERR_NOT_DIRECTORY;
    if (!vfs_check_access(dir, VFS_ACCESS_WRITE))
        return VFS_ERR_ACCESS_DENIED;
    if (parent->generation == ~(u64)0 || fs->next_inode == ~(u64)0)
        return VFS_ERR_NO_SPACE;
    if (!fs->cluster_bytes || !fs->sectors_per_cluster ||
        fs->cluster_bytes != fs->sectors_per_cluster * EXFAT_SECTOR_BYTES)
        return VFS_ERR_BAD_FORMAT;
    result = exfat_ownership_preflight_locked_count(dir, &scanned_entries,
                                                    NULL);
    if (result != VFS_OK) return result;
    result = exfat_find_entry_locked_view(fs, parent->first_cluster,
                                      parent->no_fat_chain,
                                      parent->data_length, name,
                                      &existing, &found);
    if (result != VFS_OK) return result;
    if (found) return VFS_ERR_ALREADY_EXISTS;

    tx = (exfat_replace_transaction_t *)kmalloc(sizeof(*tx));
    if (!tx) return VFS_ERR_NO_MEM;
    memset(tx, 0, sizeof(*tx));
    tx->creating = true;
    tx->record_id = fs->next_inode + 1U;
    tx->new_length = length;
    tx->fresh_capacity = (u32)(length / fs->cluster_bytes +
                              (length % fs->cluster_bytes != 0ULL));
    if (!exfat_build_file_set(fs, name, EXFAT_ATTR_ARCHIVE,
                              0U, 0U, 0U, false, tx->entry_set,
                              &tx->created_entry_count)) {
        result = VFS_ERR_INVALID_PARAM;
        goto before_pin;
    }
    if (tx->created_entry_count > 15U) {
        result = VFS_ERR_NO_SPACE; goto before_pin;
    }
    tx->created_state = (exfat_node_t *)kmalloc(sizeof(*tx->created_state));
    if (!tx->created_state) { result = VFS_ERR_NO_MEM; goto before_pin; }
    memset(tx->created_state, 0, sizeof(*tx->created_state));
    if (tx->fresh_capacity) {
        tx->fresh_clusters = (u32 *)kmalloc(
            (usize)tx->fresh_capacity * sizeof(u32));
        if (!tx->fresh_clusters) { result = VFS_ERR_NO_MEM; goto before_pin; }
    }
    result = exfat_create_sector_slot(fs, parent, tx);
    if (result == VFS_ERR_NO_SPACE)
        result = exfat_create_directory_growth_prepare(fs, parent,
                     dir == dir->super->root_node, scanned_entries, tx);
    if (result != VFS_OK) goto before_pin;
    fs->replace_transaction = tx;
    result = vfs_recovery_pin_begin_handoff(dir->super,
                                            exfat_replace_finish_handoff,
                                            tx, &tx->pin_id);
    if (result != VFS_OK) {
        fs->replace_transaction = NULL;
        goto before_pin;
    }
    fs->version_confident = false;
    result = exfat_replace_dirty(fs, tx);
    if (result == VFS_ERR_UNCERTAIN || result == VFS_ERR_BAD_FORMAT)
        goto uncertain;
    if (result != VFS_OK) goto cancel;
    result = exfat_create_directory_growth_reserve(fs, tx);
    if (result != VFS_OK) goto uncertain;
    result = exfat_replace_stage(fs, tx, source, context);
    if (result == VFS_ERR_UNCERTAIN || result == VFS_ERR_BAD_FORMAT)
        goto uncertain;
    if (result != VFS_OK) goto cancel;
    exfat_create_build_sector(tx);
    if (tx->directory_growth) {
        if (exfat_create_directory_growth_publish(fs, parent, tx) != VFS_OK)
            goto uncertain;
    } else {
        tx->phase = EXFAT_REPLACE_PUBLISHING;
        if (!exfat_write(fs, tx->directory_sector, 1U,
                         tx->proposed_sector)) goto uncertain;
        tx->phase = EXFAT_REPLACE_FLUSHING;
        if (!block_flush_for_id(fs->dev, fs->device_id)) goto uncertain;
    }

    exfat_node_t *state = tx->created_state;
    state->vfs_node = prepared_node;
    state->first_cluster = tx->new_first;
    state->no_fat_chain = tx->new_no_fat;
    state->attributes = EXFAT_ATTR_ARCHIVE;
    state->data_length = state->valid_data_length = length;
    state->entry_offset = tx->entry_offset;
    state->parent_cluster = parent->first_cluster;
    state->parent_no_fat_chain = tx->directory_growth &&
        tx->directory_growth->conversion ? false : parent->no_fat_chain;
    state->entry_count = tx->created_entry_count;
    strcpy(state->name, name);
    state->generation = 1U;
    state->alive = state->version_valid = true;
    state->next = fs->nodes;
    fs->nodes = state;
    prepared_node->fs_data = state;
    prepared_node->inode = tx->record_id;
    tx->created_state = NULL;
    fs->next_inode = tx->record_id;
    if (tx->directory_growth && tx->directory_growth->appended) {
        parent->data_length = tx->directory_growth->new_capacity;
        parent->valid_data_length = parent->data_length;
        if (tx->directory_growth->conversion)
            parent->no_fat_chain = false;
        vfs_nodes_update_size(dir->super, dir->inode, parent->data_length);
    }
    exfat_version_advance(parent);
    *out_facts = (vfs_file_facts_t){
        .record_id = tx->record_id,
        .generation = 1U,
        .size = length,
        .owner_uid = VFS_UID_SYSTEM,
        .permissions = EXFAT_VOLUME_PERMISSIONS,
    };
    tx->phase = EXFAT_REPLACE_HANDOFF_PUBLISHED;
    tx->handoff_pending = true;
    *out_pin = tx->pin_id;
    return VFS_OK;

cancel:
    if (exfat_replace_cancel(fs, tx) != VFS_OK) goto uncertain;
    tx->phase = EXFAT_REPLACE_HANDOFF_CANCELLED;
    tx->handoff_pending = true;
    *out_pin = tx->pin_id;
    return result;
uncertain:
    (void)vfs_recovery_pin_mark_unresolved(tx->pin_id);
    return VFS_ERR_UNCERTAIN;
before_pin:
    if (result == VFS_ERR_BAD_FORMAT) fs->version_confident = false;
    exfat_replace_free(tx);
    return result;
}

static bool exfat_write_entry_set(exfat_fs_t *fs, u32 parent_cluster,
                                  bool parent_no_fat, u64 parent_length,
                                  u64 offset,
                                  const u8 *set, u8 entry_count)
{
    u64 needed;

    if (!fs || !set || !entry_count ||
        !exfat_add_u64(offset, (u64)entry_count * EXFAT_ENTRY_BYTES,
                       &needed) ||
        !exfat_ensure_directory_capacity(fs, parent_cluster, parent_no_fat,
                                         parent_length, needed) ||
        !exfat_dir_byte_write(fs, parent_cluster, parent_no_fat, offset, set,
                              (usize)entry_count * EXFAT_ENTRY_BYTES)) return false;
    /* Do not write an end marker after a reused deleted run.  A live entry
     * set may follow that run; its existing end marker must be preserved. */
    return true;
}

static vfs_node_t *exfat_finddir(vfs_node_t *dir, const char *name)
{
    vfs_super_t *sb;
    exfat_fs_t *fs;
    exfat_node_t *private_dir;
    exfat_entry_info_t entry;

    if (!dir || !name || dir->type != VFS_TYPE_DIRECTORY || !dir->fs_data)
        return NULL;
    sb = __atomic_load_n(&dir->super, __ATOMIC_ACQUIRE);
    if (!sb || !sb->private_data) return NULL;
    fs = (exfat_fs_t *)sb->private_data;
    private_dir = (exfat_node_t *)dir->fs_data;
    if (!fs->version_confident || !private_dir->alive ||
        !private_dir->version_valid) return NULL;
    if (!exfat_find_entry(fs, private_dir->first_cluster,
                          private_dir->no_fat_chain,
                          private_dir->data_length, name, &entry)) return NULL;
    return exfat_make_node_context(sb, &entry);
}

static bool exfat_readdir(vfs_node_t *dir, u32 index, vfs_dirent_t *out_entry)
{
    vfs_super_t *sb;
    exfat_fs_t *fs;
    exfat_node_t *private_dir;
    exfat_entry_info_t entry;
    u64 offset = 0;

    if (!dir || !out_entry || dir->type != VFS_TYPE_DIRECTORY || !dir->fs_data)
        return false;
    sb = __atomic_load_n(&dir->super, __ATOMIC_ACQUIRE);
    if (!sb || !sb->private_data) return false;
    fs = (exfat_fs_t *)sb->private_data;
    private_dir = (exfat_node_t *)dir->fs_data;
    if (!fs->version_confident || !private_dir->alive ||
        !private_dir->version_valid) return false;
    for (u32 visible = 0; visible <= index; visible++) {
        if (!exfat_directory_next(fs, private_dir->first_cluster,
                                  private_dir->no_fat_chain,
                                  private_dir->data_length, &offset, &entry,
                                  false, NULL))
            return false;
        if (visible == index) {
            vfs_node_t *member = exfat_make_node_context(sb, &entry);
            if (!member) return false;
            strcpy(out_entry->name, entry.name);
            out_entry->inode = member->inode;
            out_entry->type = (entry.attributes & EXFAT_ATTR_DIRECTORY)
                ? VFS_TYPE_DIRECTORY : VFS_TYPE_FILE;
            return true;
        }
    }
    return false;
}

static bool exfat_readdir_open(vfs_node_t *dir, void **out_state)
{
    exfat_node_t *private_dir;
    exfat_directory_cursor_t *cursor;
    exfat_fs_t *fs;
    u64 capacity;

    if (!dir || !out_state || dir->type != VFS_TYPE_DIRECTORY ||
        !dir->super || !dir->fs_data) return false;
    private_dir = (exfat_node_t *)dir->fs_data;
    if (!private_dir->alive || !private_dir->version_valid) return false;
    fs = (exfat_fs_t *)dir->super->private_data;
    if (!fs || !fs->version_confident ||
        (private_dir->no_fat_chain &&
         (private_dir->valid_data_length != private_dir->data_length ||
          !exfat_directory_capacity_view(fs, private_dir->first_cluster,
              true, private_dir->data_length, &capacity, NULL))))
        return false;
    cursor = (exfat_directory_cursor_t *)kmalloc(sizeof(*cursor));
    if (!cursor) return false;
    cursor->fs = fs;
    cursor->parent = dir;
    cursor->offset = 0;
    cursor->ended = false;
    *out_state = cursor;
    return true;
}

static bool exfat_readdir_next(void *state, vfs_dirent_t *out_entry)
{
    exfat_directory_cursor_t *cursor = (exfat_directory_cursor_t *)state;
    exfat_entry_info_t entry;

    if (!cursor || !out_entry || cursor->ended) return false;
    exfat_node_t *parent = (exfat_node_t *)cursor->parent->fs_data;
    if (!cursor->fs->version_confident || !parent || !parent->alive ||
        !parent->version_valid) return false;
    /* The retained parent and operation lock make each read see one current
     * mapping. Directory growth preserves existing byte offsets. */
    if (!exfat_directory_next(cursor->fs, parent->first_cluster,
                              parent->no_fat_chain, parent->data_length,
                              &cursor->offset, &entry,
                              false, NULL)) {
        cursor->ended = true;
        return false;
    }
    vfs_node_t *member = exfat_make_node(cursor->parent, &entry);
    if (!member) return false;
    strcpy(out_entry->name, entry.name);
    out_entry->inode = member->inode;
    out_entry->type = (entry.attributes & EXFAT_ATTR_DIRECTORY)
        ? VFS_TYPE_DIRECTORY : VFS_TYPE_FILE;
    return true;
}

static void exfat_readdir_close(void *state)
{
    kfree(state);
}

static int exfat_create_internal(vfs_node_t *dir, const char *name,
                                 u16 attributes, u32 owner_uid,
                                 u32 permissions, vfs_node_t **out_node)
{
    vfs_super_t *sb;
    exfat_fs_t *fs;
    exfat_node_t *private_dir;
    exfat_entry_info_t existing;
    u8 set[(EXFAT_MAX_SECONDARY + 1U) * EXFAT_ENTRY_BYTES];
    u8 count;
    u64 offset;
    u64 previous_capacity;
    u32 first_cluster = 0;
    exfat_node_t *prepared_private = NULL;
    vfs_node_t *prepared_node = NULL;
    exfat_entry_info_t created = {0};
    bool existing_found;
    int scan_result;

    if (!dir || !name || !out_node || dir->type != VFS_TYPE_DIRECTORY ||
        !dir->fs_data || !*name) return VFS_ERR_INVALID_PARAM;
    sb = __atomic_load_n(&dir->super, __ATOMIC_ACQUIRE);
    if (!sb || !sb->private_data) return VFS_ERR_DEVICE_GONE;
    fs = (exfat_fs_t *)sb->private_data;
    private_dir = (exfat_node_t *)dir->fs_data;
    if (!fs->version_confident || !private_dir->alive ||
        !private_dir->version_valid) return VFS_ERR_UNCERTAIN;
    scan_result = exfat_find_entry_checked(
        fs, private_dir->first_cluster, private_dir->no_fat_chain,
        private_dir->data_length, name,
        &existing, &existing_found, false);
    if (scan_result != VFS_OK) return scan_result;
    if (existing_found)
        return VFS_ERR_INVALID_PARAM;
    if (!exfat_build_file_set(fs, name, attributes, 0U, 0U, 0U, false,
                              set, &count))
        return VFS_ERR_INVALID_PARAM;
    if (fs->next_inode == ~(u64)0) return VFS_ERR_NO_SPACE;
    prepared_private = (exfat_node_t *)kmalloc(sizeof(*prepared_private));
    prepared_node = (vfs_node_t *)kmalloc(sizeof(*prepared_node));
    if (!prepared_private || !prepared_node) {
        kfree(prepared_private);
        kfree(prepared_node);
        return VFS_ERR_NO_MEM;
    }
    if (!exfat_set_volume_dirty(fs, true)) {
        kfree(prepared_private);
        kfree(prepared_node);
        return fs->version_confident ? VFS_ERR_IO : VFS_ERR_UNCERTAIN;
    }
    if (attributes & EXFAT_ATTR_DIRECTORY) {
        if (!exfat_alloc_cluster(fs, &first_cluster)) {
            fs->version_confident = false;
            kfree(prepared_private);
            kfree(prepared_node);
            return VFS_ERR_UNCERTAIN;
        }
        memset(set, 0, sizeof(set));
        if (!exfat_build_file_set(fs, name, attributes, first_cluster,
                                  fs->cluster_bytes, fs->cluster_bytes, false,
                                  set, &count)) {
            if (fs->version_confident)
                (void)exfat_free_chain(fs, first_cluster, false,
                                       fs->cluster_bytes);
            fs->version_confident = false;
            kfree(prepared_private);
            kfree(prepared_node);
            return VFS_ERR_UNCERTAIN;
        }
    }
    if (!exfat_directory_capacity(fs, private_dir->first_cluster,
                                  private_dir->no_fat_chain,
                                  private_dir->data_length,
                                  &previous_capacity))
    {
        fs->version_confident = false;
        kfree(prepared_private);
        kfree(prepared_node);
        return VFS_ERR_UNCERTAIN;
    }
    if (!exfat_find_free_entries(fs, private_dir->first_cluster,
                                 private_dir->no_fat_chain,
                                 private_dir->data_length, count, &offset) ||
        !exfat_write_entry_set(fs, private_dir->first_cluster,
                               private_dir->no_fat_chain,
                               private_dir->data_length, offset, set, count)) {
        /* Entry publication may have reached media. A confirmed allocation
         * is safer to retain than to free beneath a possibly visible file. */
        fs->version_confident = false;
        kfree(prepared_private);
        kfree(prepared_node);
        return VFS_ERR_UNCERTAIN;
    }
    if (!exfat_directory_length_refresh(fs, private_dir, previous_capacity)) {
        fs->version_confident = false;
        kfree(prepared_private);
        kfree(prepared_node);
        return VFS_ERR_UNCERTAIN;
    }
    created.entry_offset = offset;
    created.parent_cluster = private_dir->first_cluster;
    created.parent_no_fat_chain = private_dir->no_fat_chain;
    created.entry_count = count;
    created.attributes = attributes;
    created.first_cluster = first_cluster;
    if (attributes & EXFAT_ATTR_DIRECTORY)
        created.valid_data_length = created.data_length = fs->cluster_bytes;
    strcpy(created.name, name);
    *out_node = exfat_attach_node(sb, &created, prepared_private,
                                  prepared_node);
    vfs_node_set_security(*out_node, owner_uid, permissions);
    exfat_version_advance(private_dir);
    return VFS_OK;
}

static int exfat_create(vfs_node_t *dir, const char *name,
                        vfs_node_t **out_node)
{
    u32 owner;
    if (!vfs_current_uid(&owner)) return VFS_ERR_ACCESS_DENIED;
    return exfat_create_internal(dir, name, 0U, owner,
                                 VFS_DEFAULT_FILE_PERMISSIONS,
                                 out_node);
}

