/* exFAT has no portable ownership/permission fields.  A mounted removable
 * volume therefore uses the same shared-volume policy for all users: the
 * kernel owns the node, while ordinary users may read and modify its data.
 * This is deliberately limited to exFAT nodes; it is not a VFS permission
 * bypass for system filesystems. */
#define EXFAT_VOLUME_PERMISSIONS \
    (VFS_DEFAULT_SYSTEM_PERMISSIONS | VFS_PERMISSION_OTHER_WRITE)

