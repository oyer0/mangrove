static u16 exfat_le16(const u8 *p)
{
    return (u16)p[0] | (u16)p[1] << 8U;
}

static u32 exfat_le32(const u8 *p)
{
    return (u32)p[0] | (u32)p[1] << 8U | (u32)p[2] << 16U |
           (u32)p[3] << 24U;
}

static u64 exfat_le64(const u8 *p)
{
    u64 value = 0;
    for (u32 i = 0; i < 8U; i++) value |= (u64)p[i] << (i * 8U);
    return value;
}

static void exfat_put16(u8 *p, u16 value)
{
    p[0] = (u8)value;
    p[1] = (u8)(value >> 8U);
}

static void exfat_put32(u8 *p, u32 value)
{
    for (u32 i = 0; i < 4U; i++) p[i] = (u8)(value >> (i * 8U));
}

static void exfat_put64(u8 *p, u64 value)
{
    for (u32 i = 0; i < 8U; i++) p[i] = (u8)(value >> (i * 8U));
}

static bool exfat_read(exfat_fs_t *fs, u64 lba, u32 count, void *buffer)
{
    if (!fs || !fs->dev || !buffer || !count ||
        lba > fs->dev->sector_count ||
        (u64)count > fs->dev->sector_count - lba) return false;
    return block_read_for_id(fs->dev, fs->device_id, lba, count, buffer);
}

static bool exfat_write(exfat_fs_t *fs, u64 lba, u32 count,
                        const void *buffer)
{
    if (!fs || !fs->dev || !buffer || !count ||
        lba > fs->dev->sector_count ||
        (u64)count > fs->dev->sector_count - lba) return false;
    bool written = block_write_for_id(fs->dev, fs->device_id, lba, count,
                                      buffer);
    if (!written) fs->version_confident = false;
    return written;
}

static bool exfat_add_u64(u64 left, u64 right, u64 *out)
{
    if (!out || left > ~(u64)0 - right) return false;
    *out = left + right;
    return true;
}

static bool exfat_mul_u64(u64 left, u64 right, u64 *out)
{
    if (!out || (left && right > ~(u64)0 / left)) return false;
    *out = left * right;
    return true;
}

static u32 exfat_boot_checksum_bytes(const u8 *data, usize length)
{
    u32 checksum = 0;

    if (!data) return 0;
    for (usize i = 0; i < length; i++) {
        /* VolumeFlags and PercentInUse are mutable fields and are excluded
         * from the exFAT boot checksum. */
        if (i == 106U || i == 107U || i == 112U) continue;
        checksum = (checksum >> 1U) | (checksum << 31U);
        checksum += data[i];
    }
    return checksum;
}

static bool exfat_read_boot_region(block_device_t *dev, u64 device_id,
                                   u64 start,
                                   exfat_boot_info_t *out)
{
    u8 boot_sector[EXFAT_SECTOR_BYTES];
    u8 sector[EXFAT_SECTOR_BYTES];
    u8 checksum_sector[EXFAT_SECTOR_BYTES];
    u8 signature[8] = { 'E','X','F','A','T',' ',' ',' ' };
    u32 checksum = 0;

    if (!dev || !out || dev->sector_size != EXFAT_SECTOR_BYTES ||
        start > dev->sector_count ||
        EXFAT_BOOT_REGION_SECTORS > dev->sector_count - start) return false;
    if (!block_read_for_id(dev, device_id, start, 1U, boot_sector) ||
        memcmp(boot_sector + 3U, signature, sizeof(signature)) != 0 ||
        boot_sector[510] != 0x55U || boot_sector[511] != 0xaaU) return false;
    for (u32 index = 0; index < 11U; index++) {
        if (!block_read_for_id(dev, device_id, start + index, 1U, sector))
            return false;
        for (u32 byte = 0; byte < EXFAT_SECTOR_BYTES; byte++) {
            u32 absolute = index * EXFAT_SECTOR_BYTES + byte;
            if (absolute == 106U || absolute == 107U || absolute == 112U)
                continue;
            checksum = (checksum >> 1U) | (checksum << 31U);
            checksum += sector[byte];
        }
    }
    if (!block_read_for_id(dev, device_id,
                           start + EXFAT_BOOT_CHECKSUM_SECTOR, 1U,
                           checksum_sector)) return false;
    for (u32 offset = 0; offset + 4U <= EXFAT_SECTOR_BYTES; offset += 4U)
        if (exfat_le32(checksum_sector + offset) != checksum) return false;

    memset(out, 0, sizeof(*out));
    out->partition_offset = exfat_le64(boot_sector + 64U);
    out->volume_length = exfat_le64(boot_sector + 72U);
    out->fat_offset = exfat_le32(boot_sector + 80U);
    out->fat_length = exfat_le32(boot_sector + 84U);
    out->heap_offset = exfat_le32(boot_sector + 88U);
    out->cluster_count = exfat_le32(boot_sector + 92U);
    out->root_cluster = exfat_le32(boot_sector + 96U);
    out->volume_serial = exfat_le32(boot_sector + 100U);
    out->revision = exfat_le16(boot_sector + 104U);
    out->volume_flags = exfat_le16(boot_sector + 106U);
    out->bytes_per_sector_shift = boot_sector[108];
    out->sectors_per_cluster_shift = boot_sector[109];
    out->fat_count = boot_sector[110];
    out->percent_in_use = boot_sector[112];

    if (out->revision < 0x0100U || out->revision > 0x0101U ||
        out->bytes_per_sector_shift != 9U ||
        out->sectors_per_cluster_shift > 11U ||
        (out->fat_count != 1U && out->fat_count != 2U) ||
        (start == EXFAT_MAIN_BOOT_LBA && out->fat_count == 1U &&
         (out->volume_flags & 1U) != 0U) ||
        out->fat_offset < 24U || !out->fat_length || !out->cluster_count ||
        out->cluster_count > 0xfffffff5U || out->root_cluster < 2U ||
        out->root_cluster > out->cluster_count + 1U) return false;
    return true;
}

static bool exfat_boot_geometry_valid(block_device_t *dev,
                                      const exfat_boot_info_t *boot)
{
    u64 fat_end;
    u64 heap_bytes;
    u64 heap_end;
    u64 fat_capacity;

    if (!dev || !boot || dev->sector_size != EXFAT_SECTOR_BYTES ||
        !boot->volume_length || boot->volume_length > dev->sector_count)
        return false;
    if (!exfat_mul_u64(boot->fat_length, boot->fat_count, &fat_capacity) ||
        !exfat_add_u64(boot->fat_offset, fat_capacity, &fat_end) ||
        fat_end > dev->sector_count || boot->heap_offset < fat_end)
        return false;
    if (!exfat_mul_u64(boot->cluster_count,
                       1ULL << boot->sectors_per_cluster_shift,
                       &heap_bytes) ||
        !exfat_add_u64(boot->heap_offset, heap_bytes, &heap_end) ||
        heap_end > boot->volume_length || heap_end > dev->sector_count)
        return false;
    fat_capacity = (u64)boot->fat_length * (EXFAT_SECTOR_BYTES / 4U);
    if ((u64)boot->cluster_count + 2ULL > fat_capacity) return false;
    return true;
}

static bool exfat_read_geometry(block_device_t *dev, u64 device_id,
                                exfat_boot_info_t *out)
{
    exfat_boot_info_t main_boot;
    exfat_boot_info_t backup_boot;

    if (!exfat_read_boot_region(dev, device_id, EXFAT_MAIN_BOOT_LBA,
                                &main_boot) ||
        !exfat_read_boot_region(dev, device_id, EXFAT_BACKUP_BOOT_LBA,
                                &backup_boot) ||
        !exfat_boot_geometry_valid(dev, &main_boot) ||
        !exfat_boot_geometry_valid(dev, &backup_boot)) return false;
    /* VolumeFlags and PercentInUse are mutable boot-region fields.  Their
     * values may legitimately differ between the main and backup copies
     * after another OS has mounted and cleanly released the volume.  The
     * structural fields must still agree exactly. */
    if (main_boot.partition_offset != backup_boot.partition_offset ||
        main_boot.volume_length != backup_boot.volume_length ||
        main_boot.fat_offset != backup_boot.fat_offset ||
        main_boot.fat_length != backup_boot.fat_length ||
        main_boot.heap_offset != backup_boot.heap_offset ||
        main_boot.cluster_count != backup_boot.cluster_count ||
        main_boot.root_cluster != backup_boot.root_cluster ||
        main_boot.volume_serial != backup_boot.volume_serial ||
        main_boot.revision != backup_boot.revision ||
        main_boot.bytes_per_sector_shift != backup_boot.bytes_per_sector_shift ||
        main_boot.sectors_per_cluster_shift !=
            backup_boot.sectors_per_cluster_shift ||
        main_boot.fat_count != backup_boot.fat_count) {
        return false;
    }
    if (out) *out = main_boot;
    return true;
}

static bool exfat_set_volume_dirty(exfat_fs_t *fs, bool dirty)
{
    u16 flags;

    if (!fs || !fs->dev || fs->dev->id != fs->device_id ||
        !block_device_id_is_live(fs->device_id)) return false;
    flags = fs->boot.volume_flags;
    if (dirty) flags |= 0x0002U;
    else flags &= (u16)~0x0002U;
    if (flags == fs->boot.volume_flags) return true;
    /* VolumeFlags is excluded from the boot-region checksum.  Keep the main
     * and backup copies synchronized, and do not proceed with a metadata
     * mutation if either protected write fails. */
    for (u64 base = EXFAT_MAIN_BOOT_LBA;
         base <= EXFAT_BACKUP_BOOT_LBA; base += EXFAT_BACKUP_BOOT_LBA) {
        u8 sector[EXFAT_SECTOR_BYTES];
        if (!exfat_read(fs, base, 1U, sector)) return false;
        exfat_put16(sector + 106U, flags);
        if (!exfat_write(fs, base, 1U, sector)) return false;
    }
    fs->boot.volume_flags = flags;
    return true;
}

static u64 exfat_cluster_lba(const exfat_fs_t *fs, u32 cluster)
{
    u64 offset;
    if (!fs || cluster < EXFAT_CLUSTER_FIRST ||
        cluster > fs->boot.cluster_count + 1U ||
        !exfat_mul_u64((u64)cluster - 2ULL, fs->sectors_per_cluster,
                       &offset) ||
        !exfat_add_u64(fs->boot.heap_offset, offset, &offset)) return ~(u64)0;
    return offset;
}

/* Read-only views are stack-owned by a locked proof/scan and die before
 * mutation or unlock. Separate FAT and stream sectors avoid mutual eviction.
 * No view is attached to a mount, node, transaction, or public directory cursor. */
typedef struct {
    u8 sector[EXFAT_SECTOR_BYTES];
    u64 lba;
    exfat_fs_t *owner;
    u64 device_id;
    bool valid;
} exfat_read_view_t;
typedef struct {
    u8 sector[EXFAT_SECTOR_BYTES];
    u64 lba, index;
    u32 first, current;
    exfat_fs_t *owner;
    u64 device_id;
    bool mapped, valid, no_fat;
} exfat_stream_view_t;

static bool exfat_view_live(exfat_fs_t *fs)
{
    return fs && fs->dev && fs->dev->id == fs->device_id &&
           block_device_id_is_live(fs->device_id);
}

static bool exfat_fat_get_view(exfat_fs_t *fs, u32 cluster, u32 *out_value, exfat_read_view_t *view)
{
    u8 scratch[EXFAT_SECTOR_BYTES];
    u8 *sector = view ? view->sector : scratch;
    u64 byte_offset;
    u64 lba;
    u32 offset;

    if (view && !exfat_view_live(fs)) { view->valid = false; return false; }
    if (view && view->valid &&
        (view->owner != fs || view->device_id != fs->device_id)) view->valid = false;
    if (!fs || !out_value || cluster > fs->boot.cluster_count + 1U ||
        !exfat_mul_u64(cluster, 4ULL, &byte_offset)) return false;
    lba = (u64)fs->boot.fat_offset + fs->active_fat * fs->boot.fat_length +
          byte_offset / EXFAT_SECTOR_BYTES;
    offset = (u32)(byte_offset % EXFAT_SECTOR_BYTES);
    if (offset > EXFAT_SECTOR_BYTES - 4U) return false;
    if (!view || !view->valid || view->lba != lba) {
        if (!exfat_read(fs, lba, 1U, sector)) {
            if (view) view->valid = false;
            return false;
        }
        if (view) {
            view->owner = fs; view->device_id = fs->device_id;
            view->lba = lba; view->valid = true;
        }
    }
    *out_value = exfat_le32(sector + offset);
    return true;
}

static bool exfat_fat_get(exfat_fs_t *fs, u32 cluster, u32 *out_value)
{
    return exfat_fat_get_view(fs, cluster, out_value, NULL);
}

static bool exfat_fat_set(exfat_fs_t *fs, u32 cluster, u32 value)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    u64 byte_offset;
    u32 offset;

    if (!fs || cluster < EXFAT_CLUSTER_FIRST ||
        cluster > fs->boot.cluster_count + 1U ||
        !exfat_mul_u64(cluster, 4ULL, &byte_offset)) return false;
    offset = (u32)(byte_offset % EXFAT_SECTOR_BYTES);
    if (offset > EXFAT_SECTOR_BYTES - 4U) return false;
    if (!exfat_read(fs, (u64)fs->boot.fat_offset +
                    fs->active_fat * fs->boot.fat_length +
                    byte_offset / EXFAT_SECTOR_BYTES, 1U, sector)) return false;
    exfat_put32(sector + offset, value);
    for (u32 fat = 0; fat < fs->boot.fat_count; fat++) {
        u64 lba = (u64)fs->boot.fat_offset + fat * fs->boot.fat_length +
                  byte_offset / EXFAT_SECTOR_BYTES;
        if (!exfat_write(fs, lba, 1U, sector)) return false;
    }
    return true;
}

static bool exfat_chain_cluster(exfat_fs_t *fs, u32 first, bool no_fat,
                                u64 index, u32 *out_cluster)
{
    u32 cluster = first;

    if (!fs || !out_cluster || first < 2U ||
        first > fs->boot.cluster_count + 1U ||
        index > EXFAT_MAX_DIRECTORY_CLUSTERS) return false;
    if (no_fat) {
        if (index > fs->boot.cluster_count + 1U - first) return false;
        *out_cluster = first + (u32)index;
        return true;
    }
    for (u64 step = 0; step < index; step++) {
        u32 next;
        if (!exfat_fat_get(fs, cluster, &next) || next < 2U ||
            next > fs->boot.cluster_count + 1U ||
            next >= EXFAT_CLUSTER_EOC_MIN)
            return false;
        cluster = next;
    }
    *out_cluster = cluster;
    return true;
}

static bool exfat_dir_byte_read(exfat_fs_t *fs, u32 first, bool no_fat,
                                u64 offset, void *buffer, usize length)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    u8 *out = (u8 *)buffer;
    u64 limit;

    if (!fs || !buffer || !length ||
        !exfat_mul_u64(fs->boot.cluster_count,
                       fs->cluster_bytes, &limit) || offset > limit ||
        (u64)length > limit - offset) return false;
    while (length) {
        u64 cluster_index = offset / fs->cluster_bytes;
        u64 within_cluster = offset % fs->cluster_bytes;
        u64 sector_index = within_cluster / EXFAT_SECTOR_BYTES;
        u32 within_sector = (u32)(within_cluster % EXFAT_SECTOR_BYTES);
        u32 cluster;
        usize amount = EXFAT_SECTOR_BYTES - within_sector;
        u64 lba;
        if ((u64)amount > length) amount = (usize)length;
        if (!exfat_chain_cluster(fs, first, no_fat, cluster_index, &cluster) ||
            (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
            !exfat_add_u64(lba, sector_index, &lba) ||
            !exfat_read(fs, lba, 1U, sector)) return false;
        memcpy(out, sector + within_sector, amount);
        out += amount;
        offset += amount;
        length -= amount;
    }
    return true;
}

/* Forward traversal, with a reset on backward access or stream changes.
 * Exact lengths/cycle/ownership proofs remain in their existing callers. */
static bool exfat_stream_cluster_view(exfat_fs_t *fs, u32 first, bool no_fat,
    u64 index, u32 *out, exfat_read_view_t *fat, exfat_stream_view_t *stream)
{
    if (!exfat_view_live(fs) || first < 2U ||
        first > fs->boot.cluster_count + 1U ||
        index > EXFAT_MAX_DIRECTORY_CLUSTERS) goto failure;
    if (!stream->mapped || stream->owner != fs ||
        stream->device_id != fs->device_id || stream->first != first ||
        stream->no_fat != no_fat || index < stream->index) {
        stream->owner = fs; stream->device_id = fs->device_id;
        stream->first = first; stream->no_fat = no_fat;
        stream->index = 0; stream->current = first;
        stream->mapped = true; stream->valid = false;
    }
    if (no_fat) {
        if (index > fs->boot.cluster_count + 1U - first) goto failure;
        stream->current = first + (u32)index;
        stream->index = index;
    } else {
        while (stream->index < index) {
            u32 next;
            if (!exfat_fat_get_view(fs, stream->current, &next, fat) ||
                next < 2U || next > fs->boot.cluster_count + 1U ||
                next >= EXFAT_CLUSTER_EOC_MIN) goto failure;
            stream->current = next;
            stream->index++;
        }
    }
    *out = stream->current;
    return true;
failure:
    stream->mapped = stream->valid = false;
    fat->valid = false;
    return false;
}

static bool exfat_dir_byte_read_view(exfat_fs_t *fs, u32 first, bool no_fat,
    u64 offset, void *buffer, usize length, exfat_read_view_t *fat,
    exfat_stream_view_t *stream)
{
    u8 *out = (u8 *)buffer;
    u64 limit;
    if (!fat || !stream)
        return exfat_dir_byte_read(fs, first, no_fat, offset, buffer, length);
    if (!fs || !buffer || !length || !fs->cluster_bytes ||
        !exfat_mul_u64(fs->boot.cluster_count, fs->cluster_bytes, &limit) ||
        offset > limit || (u64)length > limit - offset) goto failure;
    while (length) {
        u32 cluster;
        u64 within = offset % fs->cluster_bytes, lba;
        u32 at = (u32)(within % EXFAT_SECTOR_BYTES);
        usize amount = EXFAT_SECTOR_BYTES - at;
        if (amount > length) amount = length;
        if (!exfat_stream_cluster_view(fs, first, no_fat,
                offset / fs->cluster_bytes, &cluster, fat, stream) ||
            (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
            !exfat_add_u64(lba, within / EXFAT_SECTOR_BYTES, &lba)) goto failure;
        if (!stream->valid || stream->lba != lba) {
            stream->valid = false;
            if (!exfat_read(fs, lba, 1U, stream->sector)) goto failure;
            stream->lba = lba; stream->valid = true;
        }
        memcpy(out, stream->sector + at, amount);
        out += amount; offset += amount; length -= amount;
    }
    return true;
failure:
    stream->mapped = stream->valid = false;
    fat->valid = false;
    return false;
}

static bool exfat_dir_byte_write(exfat_fs_t *fs, u32 first, bool no_fat,
                                 u64 offset, const void *buffer, usize length)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    const u8 *input = (const u8 *)buffer;
    u64 limit;

    if (!fs || !buffer || !length ||
        !exfat_mul_u64(fs->boot.cluster_count, fs->cluster_bytes, &limit) ||
        offset > limit || (u64)length > limit - offset) return false;
    while (length) {
        u64 cluster_index = offset / fs->cluster_bytes;
        u64 within_cluster = offset % fs->cluster_bytes;
        u64 sector_index = within_cluster / EXFAT_SECTOR_BYTES;
        u32 within_sector = (u32)(within_cluster % EXFAT_SECTOR_BYTES);
        u32 cluster;
        usize amount = EXFAT_SECTOR_BYTES - within_sector;
        u64 lba;
        if ((u64)amount > length) amount = (usize)length;
        if (!exfat_chain_cluster(fs, first, no_fat, cluster_index, &cluster) ||
            (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
            !exfat_add_u64(lba, sector_index, &lba) ||
            !exfat_read(fs, lba, 1U, sector)) return false;
        memcpy(sector + within_sector, input, amount);
        if (!exfat_write(fs, lba, 1U, sector)) return false;
        input += amount;
        offset += amount;
        length -= amount;
    }
    return true;
}

static u32 exfat_upcase_checksum(const u8 *data, usize length)
{
    u32 checksum = 0;

    if (!data) return 0;
    for (usize i = 0; i < length; i++) {
        checksum = (checksum >> 1U) | (checksum << 31U);
        checksum += data[i];
    }
    return checksum;
}

static bool exfat_upcase_decode_valid(const u8 *data, usize length)
{
    u32 codepoint = 0;
    usize offset = 0;

    if (!data || !length || (length & 1U)) return false;
    while (offset + 2U <= length && codepoint < 0x10000U) {
        u16 value = exfat_le16(data + offset);
        offset += 2U;
        /* Dense tables contain literal mappings. At U+FFFF, FFFF is a
         * literal mapping, not a marker consuming a missing count. */
        if (value == 0xffffU && length != 0x20000U &&
            codepoint != 0xffffU) {
            u32 skip;
            if (offset + 2U > length) return false;
            /* The count includes exactly this many identity mappings. */
            skip = exfat_le16(data + offset);
            offset += 2U;
            if (!skip || skip > 0x10000U - codepoint ||
                (codepoint <= 0x7aU && codepoint + skip > 0x61U))
                return false;
            codepoint += skip;
        } else {
            /* The specification mandates these first 128 mappings. */
            if (codepoint < 128U && value !=
                (codepoint >= 0x61U && codepoint <= 0x7aU ?
                 codepoint - 0x20U : codepoint)) return false;
            codepoint++;
        }
    }
    return codepoint == 0x10000U && offset == length;
}

static u16 exfat_upcase_unit(const exfat_fs_t *fs, u16 input)
{
    u32 codepoint = 0;
    usize offset = 0;

    if (!fs || !fs->upcase) return input;
    if (fs->upcase_length == 0x20000U)
        return exfat_le16(fs->upcase + (usize)input * 2U);
    while (offset + 2U <= fs->upcase_length && codepoint <= input) {
        u16 value = exfat_le16(fs->upcase + offset);
        offset += 2U;
        if (value == 0xffffU && codepoint != 0xffffU) {
            u32 skip;
            if (offset + 2U > fs->upcase_length) return input;
            skip = exfat_le16(fs->upcase + offset);
            if (!skip || skip > 0x10000U - codepoint) return input;
            offset += 2U;
            if (input < codepoint + skip) return input;
            codepoint += skip;
        } else {
            if (codepoint == input) return value;
            codepoint++;
        }
    }
    return input;
}

static bool exfat_utf8_decode_one(const u8 *input, usize length, usize *offset,
                                  u32 *out_codepoint)
{
    usize at;
    u8 lead;
    u32 value;
    u32 minimum;
    u32 count;

    if (!input || !offset || !out_codepoint || *offset >= length) return false;
    at = *offset;
    lead = input[at++];
    if (lead < 0x80U) {
        value = lead; minimum = 0; count = 1;
    } else if (lead >= 0xc2U && lead <= 0xdfU) {
        value = lead & 0x1fU; minimum = 0x80U; count = 2;
    } else if (lead >= 0xe0U && lead <= 0xefU) {
        value = lead & 0x0fU; minimum = 0x800U; count = 3;
    } else if (lead >= 0xf0U && lead <= 0xf4U) {
        value = lead & 7U; minimum = 0x10000U; count = 4;
    } else return false;
    if (at + count - 1U > length) return false;
    for (u32 i = 1U; i < count; i++) {
        u8 byte = input[at++];
        if ((byte & 0xc0U) != 0x80U) return false;
        value = (value << 6U) | (byte & 0x3fU);
    }
    if (value < minimum || value > 0x10ffffU ||
        (value >= 0xd800U && value <= 0xdfffU)) return false;
    *offset = at;
    *out_codepoint = value;
    return true;
}

static bool exfat_name_codepoint_allowed(u32 value)
{
    if (value == 0U || value < 0x20U ||
        (value >= 0x7fU && value <= 0x9fU)) return false;
    return value != '<' && value != '>' && value != ':' && value != '"' &&
           value != '/' && value != '\\' && value != '|' && value != '?' &&
           value != '*';
}

static bool exfat_utf8_to_utf16(const char *input, u16 *output,
                                u16 *out_units, bool label)
{
    usize length;
    usize offset = 0;
    u16 units = 0;
    bool content = false;
    u32 first = 0;
    u32 last = 0;

    if (!input || !output || !out_units ||
        (length = strlen(input)) > (label ? 255U : 255U)) return false;
    while (offset < length) {
        u32 value;
        if (!exfat_utf8_decode_one((const u8 *)input, length, &offset,
                                   &value) || !exfat_name_codepoint_allowed(value))
            return false;
        if (!first) first = value;
        last = value;
        if (value != ' ' && value != '\t') content = true;
        if (value <= 0xffffU) {
            if (units >= EXFAT_MAX_NAME_UNITS) return false;
            output[units++] = (u16)value;
        } else {
            if (units > EXFAT_MAX_NAME_UNITS - 2U) return false;
            value -= 0x10000U;
            output[units++] = (u16)(0xd800U | (value >> 10U));
            output[units++] = (u16)(0xdc00U | (value & 0x3ffU));
        }
    }
    if (label && units > 11U) return false;
    if (label && units && (!content || first == ' ' || last == ' ')) return false;
    *out_units = units;
    return true;
}

static bool exfat_utf16_to_utf8(const u16 *input, u16 units, char *output,
                                usize capacity)
{
    usize position = 0;

    if (!input || !output || !capacity || units > EXFAT_MAX_NAME_UNITS)
        return false;
    for (u16 i = 0; i < units; i++) {
        u32 value = input[i];
        usize encoded;
        if (value >= 0xd800U && value <= 0xdbffU) {
            u16 low;
            if (i + 1U >= units || (low = input[++i]) < 0xdc00U ||
                low > 0xdfffU) return false;
            value = 0x10000U + ((value - 0xd800U) << 10U) +
                    (low - 0xdc00U);
        } else if (value >= 0xdc00U && value <= 0xdfffU) return false;
        if (value < 0x80U) encoded = 1U;
        else if (value < 0x800U) encoded = 2U;
        else if (value < 0x10000U) encoded = 3U;
        else encoded = 4U;
        if (position > capacity - 1U - encoded) return false;
        if (encoded == 1U) output[position++] = (char)value;
        else if (encoded == 2U) {
            output[position++] = (char)(0xc0U | (value >> 6U));
            output[position++] = (char)(0x80U | (value & 0x3fU));
        } else if (encoded == 3U) {
            output[position++] = (char)(0xe0U | (value >> 12U));
            output[position++] = (char)(0x80U | ((value >> 6U) & 0x3fU));
            output[position++] = (char)(0x80U | (value & 0x3fU));
        } else {
            output[position++] = (char)(0xf0U | (value >> 18U));
            output[position++] = (char)(0x80U | ((value >> 12U) & 0x3fU));
            output[position++] = (char)(0x80U | ((value >> 6U) & 0x3fU));
            output[position++] = (char)(0x80U | (value & 0x3fU));
        }
    }
    if (position >= capacity) return false;
    output[position] = '\0';
    return true;
}

static bool exfat_bitmap_bit(exfat_fs_t *fs, u32 cluster, bool *out_used)
{
    u8 byte;
    u64 bit;

    if (!fs || !out_used || cluster < 2U ||
        cluster > fs->boot.cluster_count + 1U) return false;
    bit = (u64)cluster - 2ULL;
    if (bit / 8ULL >= fs->bitmap_length ||
        !exfat_dir_byte_read(fs, fs->bitmap_cluster, false,
                             bit / 8ULL, &byte, 1U)) return false;
    *out_used = (byte & (1U << (bit % 8ULL))) != 0U;
    return true;
}

static bool exfat_bitmap_bit_view(exfat_fs_t *fs, u32 cluster, bool *out_used,
    exfat_read_view_t *fat, exfat_stream_view_t *stream)
{
    u8 byte;
    if (!fs || !out_used || cluster < 2U ||
        cluster > fs->boot.cluster_count + 1U) return false;
    u64 bit = (u64)cluster - 2ULL;
    if (bit / 8ULL >= fs->bitmap_length ||
        !exfat_dir_byte_read_view(fs, fs->bitmap_cluster, false, bit / 8ULL,
                                 &byte, 1U, fat, stream)) return false;
    *out_used = !!(byte & (1U << (bit % 8ULL)));
    return true;
}

static bool exfat_bitmap_set(exfat_fs_t *fs, u32 cluster, bool used)
{
    u8 byte;
    u64 bit;

    if (!fs || cluster < 2U || cluster > fs->boot.cluster_count + 1U)
        return false;
    bit = (u64)cluster - 2ULL;
    if (bit / 8ULL >= fs->bitmap_length ||
        !exfat_dir_byte_read(fs, fs->bitmap_cluster, false,
                             bit / 8ULL, &byte, 1U)) return false;
    if (used) byte |= (u8)(1U << (bit % 8ULL));
    else byte &= (u8)~(1U << (bit % 8ULL));
    return exfat_dir_byte_write(fs, fs->bitmap_cluster, false,
                                bit / 8ULL, &byte, 1U);
}

/* The allocation bitmap is itself an ordinary exFAT system stream.  Keep its
 * addressing behind the same chain validation used for every other stream;
 * formatter-created volumes use the normal contiguous form, but imported
 * media need not. */
static bool exfat_bitmap_byte_lba(exfat_fs_t *fs, u64 byte, u64 *out_lba)
{
    u32 cluster;
    u64 cluster_index;
    u64 within;
    u64 lba;

    if (!fs || !out_lba || byte >= fs->bitmap_length ||
        !fs->cluster_bytes) return false;
    cluster_index = byte / fs->cluster_bytes;
    within = byte % fs->cluster_bytes;
    if (!exfat_chain_cluster(fs, fs->bitmap_cluster, false,
                             cluster_index, &cluster) ||
        (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
        !exfat_add_u64(lba, within / EXFAT_SECTOR_BYTES, out_lba))
        return false;
    return true;
}

static bool exfat_bitmap_set_range(exfat_fs_t *fs, u32 first, u64 count,
                                   bool used)
{
    u64 first_bit;
    u64 last_bit;
    u64 first_byte;
    u64 last_byte;
    u64 sector_byte;
    u8 sector[EXFAT_SECTOR_BYTES];

    if (!fs || first < EXFAT_CLUSTER_FIRST || !count ||
        count > fs->boot.cluster_count + 1ULL - first) return false;
    first_bit = (u64)first - EXFAT_CLUSTER_FIRST;
    if (count - 1ULL > ~(u64)0 - first_bit) return false;
    last_bit = first_bit + count - 1ULL;
    first_byte = first_bit / 8ULL;
    last_byte = last_bit / 8ULL;
    if (last_byte >= fs->bitmap_length) return false;
    sector_byte = first_byte & ~(u64)(EXFAT_SECTOR_BYTES - 1U);
    for (u64 byte = sector_byte;; byte += EXFAT_SECTOR_BYTES) {
        u64 lba;
        u64 sector_byte_end;
        u32 begin;
        u32 end;

        if (!exfat_bitmap_byte_lba(fs, byte, &lba) ||
            !exfat_read(fs, lba, 1U, sector)) return false;
        sector_byte_end = byte + EXFAT_SECTOR_BYTES - 1ULL;
        begin = byte == first_byte ? (u32)(first_bit % 8ULL) : 0U;
        end = sector_byte_end >= last_byte ? (u32)(last_bit % 8ULL) : 7U;
        for (u32 at = 0; at < EXFAT_SECTOR_BYTES; at++) {
            u64 this_byte = byte + at;
            u32 bit_begin;
            u32 bit_end;
            u8 mask;

            if (this_byte < first_byte || this_byte > last_byte) continue;
            bit_begin = this_byte == first_byte ? begin : 0U;
            bit_end = this_byte == last_byte ? end : 7U;
            mask = (u8)(((1U << (bit_end - bit_begin + 1U)) - 1U) <<
                        bit_begin);
            if (used) sector[at] |= mask;
            else sector[at] &= (u8)~mask;
        }
        if (!exfat_write(fs, lba, 1U, sector)) return false;
        if (sector_byte_end >= last_byte) break;
        if (byte > ~(u64)0 - EXFAT_SECTOR_BYTES) return false;
    }
    return true;
}

static bool exfat_bitmap_range_unused(exfat_fs_t *fs, u32 first, u64 count)
{
    u64 first_bit;
    u64 last_bit;
    u64 first_byte;
    u64 last_byte;
    u64 sector_byte;
    u8 sector[EXFAT_SECTOR_BYTES];

    if (!fs || first < EXFAT_CLUSTER_FIRST || !count ||
        count > fs->boot.cluster_count + 1ULL - first) return false;
    first_bit = (u64)first - EXFAT_CLUSTER_FIRST;
    if (count - 1ULL > ~(u64)0 - first_bit) return false;
    last_bit = first_bit + count - 1ULL;
    first_byte = first_bit / 8ULL;
    last_byte = last_bit / 8ULL;
    if (last_byte >= fs->bitmap_length) return false;
    sector_byte = first_byte & ~(u64)(EXFAT_SECTOR_BYTES - 1U);
    for (u64 byte = sector_byte;; byte += EXFAT_SECTOR_BYTES) {
        u64 lba;
        u64 sector_byte_end;

        if (!exfat_bitmap_byte_lba(fs, byte, &lba) ||
            !exfat_read(fs, lba, 1U, sector)) return false;
        sector_byte_end = byte + EXFAT_SECTOR_BYTES - 1ULL;
        for (u32 at = 0; at < EXFAT_SECTOR_BYTES; at++) {
            u64 this_byte = byte + at;
            u32 bit_begin;
            u32 bit_end;
            u8 mask;

            if (this_byte < first_byte || this_byte > last_byte) continue;
            bit_begin = this_byte == first_byte ?
                (u32)(first_bit % 8ULL) : 0U;
            bit_end = this_byte == last_byte ?
                (u32)(last_bit % 8ULL) : 7U;
            mask = (u8)(((1U << (bit_end - bit_begin + 1U)) - 1U) <<
                        bit_begin);
            if (sector[at] & mask) return false;
        }
        if (sector_byte_end >= last_byte) break;
        if (byte > ~(u64)0 - EXFAT_SECTOR_BYTES) return false;
    }
    return true;
}

/* System primary entries have no NoFatChain flag. Even contiguous streams
 * require a FAT chain. Validate its exact length before reading bitmap bits. */
static int exfat_system_chain_check(exfat_fs_t *fs, u32 first, u64 length)
{
    u64 needed;
    u32 current = first;
    if (!fs || !fs->cluster_bytes || !length) return VFS_ERR_BAD_FORMAT;
    needed = length / fs->cluster_bytes + (length % fs->cluster_bytes != 0U);
    if (needed > fs->boot.cluster_count) return VFS_ERR_BAD_FORMAT;
    if (needed > EXFAT_SCAN_MAX_CLAIMS) return VFS_ERR_BUFFER_TOO_SMALL;
    for (u64 i = 0; i < needed; i++) {
        u32 next;
        if (current < 2U || (u64)current >= (u64)fs->boot.cluster_count + 2U)
            return VFS_ERR_BAD_FORMAT;
        if (!exfat_fat_get(fs, current, &next)) return VFS_ERR_IO;
        if (i + 1U == needed)
            return next == EXFAT_CLUSTER_EOC ? VFS_OK : VFS_ERR_BAD_FORMAT;
        if (next < 2U || (u64)next >= (u64)fs->boot.cluster_count + 2U)
            return VFS_ERR_BAD_FORMAT;
        current = next;
    }
    return VFS_ERR_BAD_FORMAT;
}

/* Root discovery must not repeatedly walk a cyclic chain looking for entries.
 * A half-speed cursor detects cycles in constant space; the claim budget also
 * bounds a valid but unsupported root chain before reading directory data. */
static int exfat_root_chain_check(exfat_fs_t *fs)
{
    u32 current = fs->root_cluster, slow = current;
    for (u32 count = 1U; count <= EXFAT_SCAN_MAX_CLAIMS; count++) {
        u32 next;
        if (current < 2U || (u64)current >= (u64)fs->boot.cluster_count + 2U)
            return VFS_ERR_BAD_FORMAT;
        if (!exfat_fat_get(fs, current, &next)) return VFS_ERR_IO;
        if (next == EXFAT_CLUSTER_EOC) return VFS_OK;
        if (next < 2U || (u64)next >= (u64)fs->boot.cluster_count + 2U)
            return VFS_ERR_BAD_FORMAT;
        current = next;
        if (!(count & 1U)) {
            if (!exfat_fat_get(fs, slow, &slow)) return VFS_ERR_IO;
            if (current == slow) return VFS_ERR_BAD_FORMAT;
        }
    }
    return VFS_ERR_BUFFER_TOO_SMALL;
}

static int exfat_system_streams_check(exfat_fs_t *fs);

static bool exfat_read_system_entries(exfat_fs_t *fs)
{
    exfat_read_view_t fat = {0};
    exfat_stream_view_t stream = {0};
    u64 maximum;
    u8 entry[EXFAT_ENTRY_BYTES];
    bool bitmap_found = false;
    bool upcase_found = false;
    bool label_found = false;
    bool ended = false;

    if (!fs || fs->boot.fat_count != 1U || fs->active_fat != 0U ||
        !exfat_mul_u64(fs->boot.cluster_count, fs->cluster_bytes,
                       &maximum) || exfat_root_chain_check(fs) != VFS_OK)
        return false;
    if (maximum > (u64)EXFAT_SCAN_MAX_ENTRIES * EXFAT_ENTRY_BYTES)
        maximum = (u64)EXFAT_SCAN_MAX_ENTRIES * EXFAT_ENTRY_BYTES;
    for (u64 offset = 0; offset + EXFAT_ENTRY_BYTES <= maximum;
         offset += EXFAT_ENTRY_BYTES) {
        u8 type;
        if (!exfat_dir_byte_read_view(fs, fs->root_cluster, false, offset,
                                 entry, sizeof(entry), &fat, &stream)) return false;
        type = entry[0];
        if (type == EXFAT_ENTRY_END) { ended = true; break; }
        if (type == EXFAT_ENTRY_BITMAP) {
            /* BitmapFlags is not GeneralSecondaryFlags: bit 0 selects
             * the bitmap belonging to the same-numbered FAT. */
            if (bitmap_found || (entry[1] & 1U)) return false;
            fs->bitmap_cluster = exfat_le32(entry + 20U);
            fs->bitmap_length = exfat_le64(entry + 24U);
            bitmap_found = true;
        } else if (type == EXFAT_ENTRY_UPCASE) {
            if (upcase_found) return false;
            fs->upcase_checksum = exfat_le32(entry + 4U);
            fs->upcase_cluster = exfat_le32(entry + 20U);
            fs->upcase_length = exfat_le64(entry + 24U);
            upcase_found = true;
        } else if (type == EXFAT_ENTRY_LABEL) {
            u16 units = entry[1];
            u16 values[11];
            if (label_found) return false;
            if (units > 11U) return false;
            for (u16 i = 0; i < units; i++)
                values[i] = exfat_le16(entry + 2U + (u32)i * 2U);
            if (!exfat_utf16_to_utf8(values, units, fs->label,
                                     sizeof(fs->label))) return false;
            label_found = true;
        } else if (type == EXFAT_ENTRY_FILE) {
            u8 secondary = entry[1];
            if (secondary > EXFAT_MAX_SECONDARY ||
                (u64)(secondary + 1U) * EXFAT_ENTRY_BYTES > maximum - offset)
                return false;
            offset += (u64)secondary * EXFAT_ENTRY_BYTES;
        }
    }
    if (!ended || !bitmap_found || !upcase_found || fs->bitmap_cluster < 2U ||
        fs->upcase_cluster < 2U || !fs->bitmap_length || !fs->upcase_length ||
        fs->bitmap_length < ((u64)fs->boot.cluster_count + 7ULL) / 8ULL ||
        fs->upcase_length > EXFAT_MAX_UPCASE_BYTES ||
        fs->bitmap_length > (u64)fs->boot.cluster_count * fs->cluster_bytes)
        return false;
    return true;
}

static bool exfat_load_upcase(exfat_fs_t *fs)
{
    exfat_read_view_t fat = {0};
    exfat_stream_view_t stream = {0};
    if (!fs || !fs->upcase_length || fs->upcase_length > EXFAT_MAX_UPCASE_BYTES ||
        fs->upcase_length > (u64)(usize)-1) return false;
    fs->upcase = (u8 *)kmalloc((usize)fs->upcase_length);
    if (!fs->upcase ||
        !exfat_dir_byte_read_view(fs, fs->upcase_cluster, false, 0,
                             fs->upcase, (usize)fs->upcase_length, &fat, &stream) ||
        exfat_upcase_checksum(fs->upcase, (usize)fs->upcase_length) !=
            fs->upcase_checksum ||
        !exfat_upcase_decode_valid(fs->upcase, (usize)fs->upcase_length)) {
        kfree(fs->upcase);
        fs->upcase = NULL;
        return false;
    }
    return true;
}

static void exfat_free_state(exfat_fs_t *fs)
{
    if (!fs) return;
    exfat_node_t *node = fs->nodes;
    while (node) {
        exfat_node_t *next = node->next;
        kfree(node);
        node = next;
    }
    kfree(fs->upcase);
    fs->upcase = NULL;
    kfree(fs);
}

static exfat_fs_t *exfat_new_state(block_device_t *dev)
{
    exfat_fs_t *fs;
    exfat_boot_info_t boot;
    u64 device_id;

    if (!dev) return NULL;
    device_id = dev->id;
    if (!exfat_read_geometry(dev, device_id, &boot)) return NULL;
    /* Two FATs imply TexFAT, not mirrored ordinary exFAT. No TexFAT
     * transaction protocol is implemented, so admit neither reads nor writes. */
    /* Dirty-on-arrival requires recovery before clearing VolumeDirty.
     * MediaFailure and ClearToZero also need a protocol we do not provide. */
    if (boot.fat_count != 1U || (boot.volume_flags & 0x000eU)) return NULL;
    fs = (exfat_fs_t *)kmalloc(sizeof(*fs));
    if (!fs) return NULL;
    memset(fs, 0, sizeof(*fs));
    fs->dev = dev;
    fs->device_id = device_id;
    fs->version_confident = true;
    fs->boot = boot;
    fs->sector_size = EXFAT_SECTOR_BYTES;
    fs->sectors_per_cluster = 1U << boot.sectors_per_cluster_shift;
    if (boot.bytes_per_sector_shift >= 32U - boot.sectors_per_cluster_shift) {
        kfree(fs);
        return NULL;
    }
    fs->cluster_bytes = 1U <<
        (boot.bytes_per_sector_shift + boot.sectors_per_cluster_shift);
    fs->active_fat = boot.volume_flags & 1U;
    fs->root_cluster = boot.root_cluster;
    if (fs->cluster_bytes > EXFAT_MAX_CLUSTER_BYTES ||
        !exfat_read_system_entries(fs) ||
        exfat_system_streams_check(fs) != VFS_OK || !exfat_load_upcase(fs)) {
        exfat_free_state(fs);
        return NULL;
    }
    return fs;
}

static bool exfat_probe(block_device_t *dev)
{
    exfat_fs_t *fs = exfat_new_state(dev);
    if (!fs) return false;
    exfat_free_state(fs);
    return true;
}

static bool exfat_read_label_internal(block_device_t *dev, char *out,
                                      usize capacity)
{
    exfat_fs_t *fs;
    bool present;

    if (!out || capacity < 2U) return false;
    out[0] = '\0';
    fs = exfat_new_state(dev);
    if (!fs) return false;
    present = fs->label[0] != '\0' && strlen(fs->label) < capacity;
    if (present) strcpy(out, fs->label);
    exfat_free_state(fs);
    return present;
}

static u64 exfat_entry_checksum(const u8 *set, u32 count)
{
    u16 checksum = 0;
    u32 bytes;

    if (!set || !count) return 0;
    if (count > ~(u32)0 / EXFAT_ENTRY_BYTES) return 0;
    bytes = count * EXFAT_ENTRY_BYTES;
    /* The exFAT checksum covers every byte in the set except the two-byte
     * checksum field in the primary file entry (the first entry).  The
     * excluded bytes are skipped entirely, including the rotate step. */
    for (u32 index = 0; index < bytes; index++) {
        u8 value;
        if (index == 2U || index == 3U) continue;
        value = set[index];
        checksum = (u16)(((checksum & 1U) ? 0x8000U : 0U) |
                         (checksum >> 1U));
        checksum = (u16)(checksum + value);
    }
    return checksum;
}

static u16 exfat_name_hash(const exfat_fs_t *fs, const u16 *name, u16 units)
{
    u16 hash = 0;
    if (!fs || !name) return 0;
    for (u16 i = 0; i < units; i++) {
        u16 value = exfat_upcase_unit(fs, name[i]);
        hash = (u16)(((hash & 1U) ? 0x8000U : 0U) | (hash >> 1U));
        hash = (u16)(hash + (value & 0xffU));
        hash = (u16)(((hash & 1U) ? 0x8000U : 0U) | (hash >> 1U));
        hash = (u16)(hash + (value >> 8U));
    }
    return hash;
}

static bool exfat_entry_set_read_checked_view(exfat_fs_t *fs, u32 parent_cluster,
                                         bool parent_no_fat, u64 offset,
                                         exfat_entry_info_t *out,
                                         bool *io_error, exfat_read_view_t *fat,
                                         exfat_stream_view_t *stream)
{
    u8 set[(EXFAT_MAX_SECONDARY + 1U) * EXFAT_ENTRY_BYTES];
    u8 secondary;
    u16 units = 0;
    u32 expected_name_entries;

    if (io_error) *io_error = false;
    if (!fs || !out || offset & (EXFAT_ENTRY_BYTES - 1U)) return false;
    if (!exfat_dir_byte_read_view(fs, parent_cluster, parent_no_fat, offset,
                             set, EXFAT_ENTRY_BYTES, fat, stream)) {
        if (io_error) *io_error = true;
        return false;
    }
    if (set[0] != EXFAT_ENTRY_FILE) return false;
    secondary = set[1];
    if (secondary < 2U || secondary > EXFAT_MAX_SECONDARY) return false;
    if (!exfat_dir_byte_read_view(fs, parent_cluster, parent_no_fat, offset,
                             set, (secondary + 1U) * EXFAT_ENTRY_BYTES, fat, stream)) {
        if (io_error) *io_error = true;
        return false;
    }
    if (exfat_entry_checksum(set, secondary + 1U) != exfat_le16(set + 2U))
        return false;
    if (set[EXFAT_ENTRY_BYTES] != EXFAT_ENTRY_STREAM ||
        set[EXFAT_ENTRY_BYTES + 3U] > EXFAT_MAX_NAME_UNITS) return false;
    expected_name_entries = (set[EXFAT_ENTRY_BYTES + 3U] + 14U) / 15U;
    if (secondary != expected_name_entries + 1U) return false;
    for (u32 i = 0; i < expected_name_entries; i++) {
        u8 *entry = set + (2U + i) * EXFAT_ENTRY_BYTES;
        if (entry[0] != EXFAT_ENTRY_NAME ||
            (entry[1] & EXFAT_STREAM_FLAGS) != 0U) return false;
        for (u32 j = 0; j < 15U && units < EXFAT_MAX_NAME_UNITS; j++)
            out->name_units[units++] = exfat_le16(entry + 2U + j * 2U);
    }
    out->name_length = set[EXFAT_ENTRY_BYTES + 3U];
    if (units < out->name_length ||
        !exfat_utf16_to_utf8(out->name_units, out->name_length, out->name,
                             sizeof(out->name))) return false;
    if (exfat_name_hash(fs, out->name_units, out->name_length) !=
        exfat_le16(set + EXFAT_ENTRY_BYTES + 4U)) return false;
    memset(out, 0, sizeof(*out));
    /* The conversion above filled fields that must survive the clear. */
    out->name_length = set[EXFAT_ENTRY_BYTES + 3U];
    for (u16 i = 0; i < out->name_length; i++) {
        u32 entry = 2U + i / 15U;
        u32 at = i % 15U;
        out->name_units[i] = exfat_le16(set + entry * EXFAT_ENTRY_BYTES +
                                         2U + at * 2U);
    }
    if (!exfat_utf16_to_utf8(out->name_units, out->name_length, out->name,
                             sizeof(out->name))) return false;
    out->entry_offset = offset;
    out->parent_cluster = parent_cluster;
    out->parent_no_fat_chain = parent_no_fat;
    out->entry_count = secondary + 1U;
    out->attributes = exfat_le16(set + 4U);
    out->stream_flags = exfat_le16(set + EXFAT_ENTRY_BYTES + 1U);
    out->valid_data_length = exfat_le64(set + EXFAT_ENTRY_BYTES + 8U);
    out->first_cluster = exfat_le32(set + EXFAT_ENTRY_BYTES + 20U);
    out->data_length = exfat_le64(set + EXFAT_ENTRY_BYTES + 24U);
    if (!(out->stream_flags & EXFAT_STREAM_ALLOCATION_POSSIBLE) ||
        ((out->stream_flags & EXFAT_STREAM_NO_FAT_CHAIN) &&
         !out->data_length) ||
        out->valid_data_length > out->data_length ||
        ((out->data_length || out->valid_data_length) &&
         (out->first_cluster < 2U ||
          out->first_cluster > fs->boot.cluster_count + 1U))) return false;
    if (out->attributes & EXFAT_ATTR_DIRECTORY) {
        if (!fs->cluster_bytes ||
            out->data_length != out->valid_data_length ||
            out->data_length % fs->cluster_bytes ||
            out->data_length > 256ULL * 1024ULL * 1024ULL)
            return false;
        if ((out->stream_flags & EXFAT_STREAM_NO_FAT_CHAIN) &&
            out->data_length / fs->cluster_bytes >
                (u64)fs->boot.cluster_count + 2ULL - out->first_cluster)
            return false;
    }
    return true;
}

static bool exfat_entry_set_read_checked(exfat_fs_t *fs, u32 parent_cluster,
    bool parent_no_fat, u64 offset, exfat_entry_info_t *out, bool *io_error)
{
    return exfat_entry_set_read_checked_view(fs, parent_cluster, parent_no_fat,
                                             offset, out, io_error, NULL, NULL);
}

static bool exfat_entry_set_read(exfat_fs_t *fs, u32 parent_cluster,
                                 bool parent_no_fat, u64 offset,
                                 exfat_entry_info_t *out)
{
    return exfat_entry_set_read_checked(fs, parent_cluster, parent_no_fat,
                                        offset, out, NULL);
}

static bool exfat_directory_capacity_view(exfat_fs_t *fs, u32 first,
    bool no_fat, u64 stream_length, u64 *out_bytes, exfat_read_view_t *fat)
{
    u64 clusters = 0;
    u32 cluster = first;

    if (!fs || !out_bytes || !fs->cluster_bytes || first < 2U ||
        first > fs->boot.cluster_count + 1U) return false;
    if (no_fat) {
        if (!stream_length || stream_length % fs->cluster_bytes ||
            stream_length > 256ULL * 1024ULL * 1024ULL ||
            stream_length / fs->cluster_bytes >
                (u64)fs->boot.cluster_count + 2ULL - first)
            return false;
        *out_bytes = stream_length;
        return true;
    }
    for (;;) {
        u32 next;
        if (++clusters > fs->boot.cluster_count) return false;
        if (!exfat_mul_u64(clusters, fs->cluster_bytes, out_bytes)) return false;
        if (!exfat_fat_get_view(fs, cluster, &next, fat)) return false;
        if (next >= EXFAT_CLUSTER_EOC_MIN) return true;
        if (next < 2U || next > fs->boot.cluster_count + 1U) return false;
        cluster = next;
    }
}

static bool exfat_directory_capacity(exfat_fs_t *fs, u32 first,
    bool no_fat, u64 stream_length, u64 *out_bytes)
{
    return exfat_directory_capacity_view(fs, first, no_fat, stream_length,
                                         out_bytes, NULL);
}

static bool exfat_zero_cluster(exfat_fs_t *fs, u32 cluster)
{
    u8 zero[EXFAT_SECTOR_BYTES * 8U];
    u64 lba;

    if (!fs || (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0) return false;
    memset(zero, 0, sizeof(zero));
    for (u32 i = 0; i < fs->sectors_per_cluster;) {
        u32 batch = fs->sectors_per_cluster - i;
        if (batch > 8U) batch = 8U;
        if (!exfat_write(fs, lba + i, batch, zero)) return false;
        i += batch;
    }
    return true;
}

static bool exfat_alloc_cluster(exfat_fs_t *fs, u32 *out_cluster)
{
    if (!fs || !out_cluster) return false;
    for (u32 cluster = 2U; cluster <= fs->boot.cluster_count + 1U; cluster++) {
        bool used;
        if (!exfat_bitmap_bit(fs, cluster, &used)) return false;
        if (used) continue;
        if (!exfat_bitmap_set(fs, cluster, true) ||
            !exfat_fat_set(fs, cluster, EXFAT_CLUSTER_EOC) ||
            !exfat_zero_cluster(fs, cluster)) {
            if (fs->version_confident)
                (void)exfat_bitmap_set(fs, cluster, false);
            fs->version_confident = false;
            return false;
        }
        *out_cluster = cluster;
        return true;
    }
    return false;
}

static bool exfat_free_chain(exfat_fs_t *fs, u32 first, bool no_fat,
                             u64 byte_length)
{
    u64 count;
    u32 cluster = first;
    bool ended = false;

    if (!fs || first < 2U) return true;
    if (no_fat) {
        if (byte_length > ~(u64)0 - (fs->cluster_bytes - 1ULL))
            return false;
        count = (byte_length + fs->cluster_bytes - 1ULL) /
                fs->cluster_bytes;
        if (!count) count = 1U;
    } else {
        count = fs->boot.cluster_count;
    }
    /* Validate the complete chain before changing allocation metadata.  A
     * corrupt loop or out-of-range link must not result in a partially freed
     * file that is harder to diagnose or recover. */
    if (no_fat) {
        if (count > fs->boot.cluster_count + 1U - first) return false;
        ended = true;
    } else {
        for (u64 step = 0; step < count; step++) {
            u32 next;
            if (cluster < EXFAT_CLUSTER_FIRST ||
                cluster > fs->boot.cluster_count + 1U ||
                !exfat_fat_get(fs, cluster, &next)) return false;
            if (next >= EXFAT_CLUSTER_EOC_MIN) {
                ended = true;
                break;
            }
            if (next < EXFAT_CLUSTER_FIRST ||
                next > fs->boot.cluster_count + 1U) return false;
            cluster = next;
        }
        if (!ended) return false;
    }
    cluster = first;
    for (u64 step = 0; step < count; step++) {
        u32 next = EXFAT_CLUSTER_EOC;
        if (cluster < EXFAT_CLUSTER_FIRST ||
            cluster > fs->boot.cluster_count + 1U) return false;
        if (!no_fat && !exfat_fat_get(fs, cluster, &next)) return false;
        if (!exfat_bitmap_set(fs, cluster, false)) return false;
        if (!no_fat && !exfat_fat_set(fs, cluster, 0U)) return false;
        if (no_fat) {
            if (cluster == fs->boot.cluster_count + 1U) {
                ended = true;
                break;
            }
            cluster++;
        } else {
            if (next >= EXFAT_CLUSTER_EOC_MIN) {
                ended = true;
                break;
            }
            if (next < 2U || next > fs->boot.cluster_count + 1U) return false;
            cluster = next;
        }
    }
    return ended;
}

static bool exfat_append_directory_cluster(exfat_fs_t *fs, u32 first,
                                            u32 *out_cluster)
{
    u32 last = first;
    u32 next;
    u32 added = 0;
    bool ended = false;

    if (!fs || first < 2U || !out_cluster) return false;
    for (u64 steps = 0; steps < fs->boot.cluster_count; steps++) {
        if (!exfat_fat_get(fs, last, &next)) return false;
        if (next >= EXFAT_CLUSTER_EOC_MIN) {
            ended = true;
            break;
        }
        if (next < 2U || next > fs->boot.cluster_count + 1U) return false;
        last = next;
    }
    if (!ended) return false;
    if (!exfat_alloc_cluster(fs, &added) ||
        !exfat_fat_set(fs, last, added)) {
        if (added >= 2U && fs->version_confident)
            (void)exfat_free_chain(fs, added, false, fs->cluster_bytes);
        return false;
    }
    *out_cluster = added;
    return true;
}

static bool exfat_ensure_directory_capacity(exfat_fs_t *fs, u32 first,
    bool no_fat, u64 stream_length, u64 needed)
{
    u64 capacity;

    if (!exfat_directory_capacity(fs, first, no_fat, stream_length,
                                  &capacity)) return false;
    while (capacity < needed) {
        u32 added;
        if (no_fat || !exfat_append_directory_cluster(fs, first, &added) ||
            !exfat_add_u64(capacity, fs->cluster_bytes, &capacity)) return false;
    }
    return true;
}

static bool exfat_find_free_entries(exfat_fs_t *fs, u32 first, bool no_fat,
    u64 stream_length, u32 count, u64 *out_offset)
{
    u64 capacity;
    u64 extra;
    u64 needed;
    u64 start;
    u64 entries_bytes;
    u32 run = 0;
    u64 run_start = 0;
    u8 entry[EXFAT_ENTRY_BYTES];

    if (!fs || !out_offset || !count ||
        !exfat_directory_capacity(fs, first, no_fat, stream_length,
                                  &capacity) ||
        !exfat_mul_u64((u64)count, EXFAT_ENTRY_BYTES, &entries_bytes))
        return false;
    for (u64 offset = 0; offset + EXFAT_ENTRY_BYTES <= capacity;
         offset += EXFAT_ENTRY_BYTES) {
        if (!exfat_dir_byte_read(fs, first, no_fat, offset, entry,
                                 sizeof(entry))) return false;
        if (!(entry[0] & 0x80U)) {
            if (!run) run_start = offset;
            if (++run == count) {
                if (!exfat_add_u64(run_start, entries_bytes, &needed))
                    return false;
                if (needed == capacity) {
                    /* Keep an end marker after a set that exactly fills
                     * the current directory extent.  The newly allocated
                     * cluster is zeroed by exfat_alloc_cluster(), so its
                     * first entry supplies that marker. */
                    if (!exfat_add_u64(capacity, EXFAT_ENTRY_BYTES, &needed) ||
                        !exfat_ensure_directory_capacity(fs, first, no_fat,
                                                         stream_length,
                                                         needed)) return false;
                }
                *out_offset = run_start;
                return true;
            }
        } else run = 0;
    }
    extra = entries_bytes;
    if (!exfat_add_u64(run ? run_start : capacity, extra, &needed) ||
        !exfat_ensure_directory_capacity(fs, first, no_fat,
                                         stream_length, needed))
        return false;
    /* The end marker is part of the free tail.  If a set does not fit in
     * that tail, start at its first free entry and let the set cross into
     * the newly appended cluster.  Starting at `capacity` would leave the
     * old end marker in place, causing standard exFAT readers to stop before
     * the new entry set. */
    start = run ? run_start : capacity;
    *out_offset = start;
    return true;
}

static bool exfat_directory_next_view(exfat_fs_t *fs, u32 first, bool no_fat,
                                 u64 stream_length, u64 *io_offset,
                                 exfat_entry_info_t *out,
                                 bool include_system, bool *out_error,
                                 exfat_read_view_t *fat, exfat_stream_view_t *stream)
{
    u64 maximum;
    u8 entry[EXFAT_ENTRY_BYTES];

    if (out_error) *out_error = false;
    if (!fs || !io_offset || !out ||
        !exfat_mul_u64(fs->boot.cluster_count, fs->cluster_bytes, &maximum)) {
        if (out_error) *out_error = true;
        return false;
    }
    if (no_fat && !exfat_directory_capacity_view(fs, first, true,
            stream_length, &maximum, fat)) {
        if (out_error) *out_error = true;
        return false;
    }
    while (*io_offset + EXFAT_ENTRY_BYTES <= maximum) {
        u64 offset = *io_offset;
        u8 type;
        if (!exfat_dir_byte_read_view(fs, first, no_fat, offset, entry,
                                 sizeof(entry), fat, stream)) {
            if (out_error) *out_error = true;
            return false;
        }
        type = entry[0];
        if (type == EXFAT_ENTRY_END) return false;
        if (type == EXFAT_ENTRY_FILE) {
            if (entry[1] < 2U || entry[1] > EXFAT_MAX_SECONDARY ||
                ((u64)entry[1] + 1ULL) * EXFAT_ENTRY_BYTES >
                    maximum - offset) {
                if (out_error) *out_error = true;
                return false;
            }
            if (!exfat_entry_set_read_checked_view(fs, first, no_fat, offset, out,
                                                     NULL, fat, stream)) {
                if (out_error) *out_error = true;
                return false;
            }
            *io_offset += (u64)out->entry_count * EXFAT_ENTRY_BYTES;
            if (!include_system && (out->attributes & EXFAT_ATTR_SYSTEM))
                continue;
            return true;
        }
        /* A live secondary outside a validated primary set is an orphan.
         * Never skip it while searching for reusable namespace slots. */
        if ((type & 0xc0U) == 0xc0U || type == 0x80U) {
            if (out_error) *out_error = true;
            return false;
        }
        *io_offset += EXFAT_ENTRY_BYTES;
    }
    if (no_fat && out_error) *out_error = true;
    return false;
}

static bool exfat_directory_next(exfat_fs_t *fs, u32 first, bool no_fat,
    u64 stream_length, u64 *io_offset, exfat_entry_info_t *out,
    bool include_system, bool *out_error)
{
    return exfat_directory_next_view(fs, first, no_fat, stream_length,
                                     io_offset, out,
                                     include_system, out_error, NULL, NULL);
}

typedef struct {
    u32 first;
    u64 length;
    bool no_fat;
    bool root;
    bool inside_target;
} exfat_scan_directory_t;

typedef struct {
    exfat_fs_t *fs;
    exfat_node_t *target;
    u8 *owned;
    exfat_scan_directory_t *pending;
    u32 queued, capacity, head, claimed, entries;
    bool found_target, found_bitmap, found_upcase;
    u32 rename_destination;
    exfat_read_view_t fat;
    exfat_stream_view_t bitmap;
} exfat_ownership_scan_t;

static int exfat_scan_enqueue(exfat_ownership_scan_t *scan,
                              exfat_scan_directory_t job)
{
    if (scan->queued == scan->capacity) {
        u32 capacity = scan->capacity ? scan->capacity * 2U : 16U;
        exfat_scan_directory_t *pending;
        if (capacity > EXFAT_SCAN_MAX_DIRECTORIES)
            return VFS_ERR_BUFFER_TOO_SMALL;
        pending = (exfat_scan_directory_t *)kmalloc(
            (usize)capacity * sizeof(*pending));
        if (!pending) return VFS_ERR_NO_MEM;
        if (scan->queued)
            memcpy(pending, scan->pending,
                   (usize)scan->queued * sizeof(*pending));
        kfree(scan->pending);
        scan->pending = pending;
        scan->capacity = capacity;
    }
    scan->pending[scan->queued++] = job;
    return VFS_OK;
}

static int exfat_scan_claim(exfat_ownership_scan_t *scan, u32 cluster)
{
    bool used;
    u32 index;
    u8 mask;

    if (cluster < 2U || (u64)cluster >= (u64)scan->fs->boot.cluster_count + 2ULL)
        return VFS_ERR_BAD_FORMAT;
    index = cluster - 2U;
    mask = (u8)(1U << (index & 7U));
    if (scan->owned[index / 8U] & mask) return VFS_ERR_BAD_FORMAT;
    if (scan->claimed == EXFAT_SCAN_MAX_CLAIMS)
        return VFS_ERR_BUFFER_TOO_SMALL;
    if (!exfat_bitmap_bit_view(scan->fs, cluster, &used, &scan->fat, &scan->bitmap)) return VFS_ERR_IO;
    if (!used) return VFS_ERR_BAD_FORMAT;
    scan->owned[index / 8U] |= mask;
    scan->claimed++;
    return VFS_OK;
}

/* Claims the entire mapping, not merely the logical bytes a reader uses.
 * FAT-linked streams must have exactly the number of clusters declared by
 * DataLength; the root has no stream entry and is followed to EOC. */
static int exfat_scan_mapping(exfat_ownership_scan_t *scan, u32 first,
                              bool no_fat, u64 length, bool root,
                              u64 *out_bytes)
{
    exfat_fs_t *fs = scan->fs;
    u64 needed, count = 0;
    u32 current = first;

    if (!fs->cluster_bytes) return VFS_ERR_BAD_FORMAT;
    needed = length / fs->cluster_bytes +
             (length % fs->cluster_bytes != 0ULL);
    if (!root && !needed) {
        if (first) return VFS_ERR_BAD_FORMAT;
        if (out_bytes) *out_bytes = 0;
        return VFS_OK;
    }
    if (first < 2U || (u64)first >= (u64)fs->boot.cluster_count + 2ULL ||
        (!root && needed > fs->boot.cluster_count))
        return VFS_ERR_BAD_FORMAT;
    if (no_fat) {
        if (root || needed > (u64)fs->boot.cluster_count + 2ULL - first)
            return VFS_ERR_BAD_FORMAT;
        for (u64 index = 0; index < needed; index++) {
            int result = exfat_scan_claim(scan, first + (u32)index);
            if (result != VFS_OK) return result;
        }
        count = needed;
    } else {
        for (;;) {
            u32 next;
            int result = exfat_scan_claim(scan, current);
            if (result != VFS_OK) return result;
            count++;
            if (!exfat_fat_get_view(fs, current, &next, &scan->fat)) return VFS_ERR_IO;
            if (next >= EXFAT_CLUSTER_EOC_MIN) break;
            if (next < 2U || (u64)next >=
                (u64)fs->boot.cluster_count + 2ULL) return VFS_ERR_BAD_FORMAT;
            current = next;
        }
        if (!root && count != needed) return VFS_ERR_BAD_FORMAT;
    }
    if (out_bytes) {
        if (!exfat_mul_u64(count, fs->cluster_bytes, out_bytes))
            return VFS_ERR_BAD_FORMAT;
    }
    return VFS_OK;
}

/* Bounded mount admission: validate chains before trusting bitmap contents,
 * then prove allocation and disjoint ownership of root and system streams.
 * The namespace-wide mutation proof remains separate and unchanged. */
static int exfat_system_streams_check(exfat_fs_t *fs)
{
    exfat_ownership_scan_t scan = {0};
    usize bytes;
    int result;
    if (!fs || fs->boot.fat_count != 1U || fs->active_fat != 0U)
        return VFS_ERR_UNSUPPORTED;
    result = exfat_system_chain_check(fs, fs->bitmap_cluster, fs->bitmap_length);
    if (result != VFS_OK) return result;
    result = exfat_system_chain_check(fs, fs->upcase_cluster, fs->upcase_length);
    if (result != VFS_OK) return result;
    bytes = ((usize)fs->boot.cluster_count + 7U) / 8U;
    if (!bytes || bytes > EXFAT_SCAN_MAX_BITMAP_BYTES)
        return VFS_ERR_BUFFER_TOO_SMALL;
    scan.fs = fs;
    scan.owned = (u8 *)kmalloc(bytes);
    if (!scan.owned) return VFS_ERR_NO_MEM;
    memset(scan.owned, 0, bytes);
    result = exfat_scan_mapping(&scan, fs->bitmap_cluster, false,
                                fs->bitmap_length, false, NULL);
    if (result == VFS_OK)
        result = exfat_scan_mapping(&scan, fs->upcase_cluster, false,
                                    fs->upcase_length, false, NULL);
    if (result == VFS_OK)
        result = exfat_scan_mapping(&scan, fs->root_cluster, false, 0U, true, NULL);
    kfree(scan.owned);
    return result;
}

static int exfat_scan_directory(exfat_ownership_scan_t *scan,
                                const exfat_scan_directory_t *directory)
{
    exfat_stream_view_t stream = {0};
    exfat_fs_t *fs = scan->fs;
    u64 capacity;
    bool ended = false;
    int result = exfat_scan_mapping(scan, directory->first,
                                    directory->no_fat, directory->length,
                                    directory->root, &capacity);
    if (result != VFS_OK) return result;
    if (!capacity || capacity / EXFAT_ENTRY_BYTES > EXFAT_SCAN_MAX_ENTRIES -
                                                 scan->entries)
        return VFS_ERR_BUFFER_TOO_SMALL;
    scan->entries += (u32)(capacity / EXFAT_ENTRY_BYTES);
    for (u64 offset = 0; offset < capacity;) {
        u8 entry[EXFAT_ENTRY_BYTES];
        u8 type;
        if (!exfat_dir_byte_read_view(fs, directory->first, directory->no_fat,
                                 offset, entry, sizeof(entry), &scan->fat, &stream)) return VFS_ERR_IO;
        type = entry[0];
        if (type == EXFAT_ENTRY_END) { ended = true; break; }
        if (!(type & 0x80U)) { offset += EXFAT_ENTRY_BYTES; continue; }
        if (type == EXFAT_ENTRY_FILE) {
            exfat_entry_info_t item = {0};
            bool is_dir;
            bool io_error;
            if (entry[1] < 2U || entry[1] > EXFAT_MAX_SECONDARY ||
                ((u64)entry[1] + 1ULL) * EXFAT_ENTRY_BYTES >
                    capacity - offset) return VFS_ERR_BAD_FORMAT;
            if (!exfat_entry_set_read_checked_view(fs, directory->first,
                                              directory->no_fat, offset,
                                              &item, &io_error, &scan->fat, &stream))
                return io_error ? VFS_ERR_IO : VFS_ERR_BAD_FORMAT;
            if ((u64)item.entry_count * EXFAT_ENTRY_BYTES > capacity - offset)
                return VFS_ERR_BAD_FORMAT;
            is_dir = !!(item.attributes & EXFAT_ATTR_DIRECTORY);
            if (item.stream_flags & ~EXFAT_STREAM_FLAGS)
                return VFS_ERR_BAD_FORMAT;
            if (item.attributes & ~(EXFAT_ATTR_READ_ONLY | EXFAT_ATTR_HIDDEN |
                                    EXFAT_ATTR_SYSTEM | EXFAT_ATTR_DIRECTORY |
                                    EXFAT_ATTR_ARCHIVE)) return VFS_ERR_BAD_FORMAT;
            /* The parent may have converted from a contiguous prefix to a
             * FAT chain while this opened child retained its original slot.
             * The slot and file facts identify the record; the parent's
             * allocation mode is only a mapping detail. */
            if (scan->target && scan->target->parent_cluster == directory->first &&
                scan->target->entry_offset == offset) {
                if (scan->found_target || scan->target->first_cluster !=
                    item.first_cluster || scan->target->data_length !=
                    item.data_length || scan->target->valid_data_length !=
                    item.valid_data_length || scan->target->attributes !=
                    item.attributes || scan->target->entry_count !=
                    item.entry_count || scan->target->no_fat_chain !=
                    !!(item.stream_flags & EXFAT_STREAM_NO_FAT_CHAIN) ||
                    strcmp(scan->target->name, item.name) ||
                    (!scan->target->vfs_node ||
                     (scan->target->vfs_node->type == VFS_TYPE_DIRECTORY) !=
                         is_dir))
                    return VFS_ERR_BAD_FORMAT;
                scan->found_target = true;
            }
            if (is_dir) {
                if (item.valid_data_length != item.data_length)
                    return VFS_ERR_BAD_FORMAT;
                if (!item.data_length) return VFS_ERR_BAD_FORMAT;
                bool inside = directory->inside_target ||
                    (scan->target && scan->target->vfs_node->type ==
                        VFS_TYPE_DIRECTORY && scan->target->first_cluster ==
                        item.first_cluster);
                if (inside && scan->rename_destination == item.first_cluster)
                    return VFS_ERR_INVALID_PARAM;
                result = exfat_scan_enqueue(scan, (exfat_scan_directory_t){
                    item.first_cluster, item.data_length,
                    !!(item.stream_flags & EXFAT_STREAM_NO_FAT_CHAIN), false,
                    inside});
                if (result != VFS_OK) return result;
            } else {
                result = exfat_scan_mapping(scan, item.first_cluster,
                    !!(item.stream_flags & EXFAT_STREAM_NO_FAT_CHAIN),
                    item.data_length, false, NULL);
                if (result != VFS_OK) return result;
            }
            offset += (u64)item.entry_count * EXFAT_ENTRY_BYTES;
            continue;
        }
        if (directory->root && type == EXFAT_ENTRY_BITMAP) {
            if (scan->found_bitmap || (entry[1] & 1U) || exfat_le32(entry + 20U) !=
                fs->bitmap_cluster || exfat_le64(entry + 24U) !=
                fs->bitmap_length) return VFS_ERR_BAD_FORMAT;
            scan->found_bitmap = true;
        } else if (directory->root && type == EXFAT_ENTRY_UPCASE) {
            if (scan->found_upcase || exfat_le32(entry + 20U) !=
                fs->upcase_cluster || exfat_le64(entry + 24U) !=
                fs->upcase_length || exfat_le32(entry + 4U) !=
                fs->upcase_checksum) return VFS_ERR_BAD_FORMAT;
            scan->found_upcase = true;
        } else if (directory->root && type == EXFAT_ENTRY_LABEL) {
            if (entry[1] > 11U) return VFS_ERR_BAD_FORMAT;
        } else return VFS_ERR_BAD_FORMAT;
        offset += EXFAT_ENTRY_BYTES;
    }
    return ended ? VFS_OK : VFS_ERR_BAD_FORMAT;
}

/* Caller holds the mount operation lock through this proof and its use.
 * No media mutation occurs. The result expires on unlocking. */
static int exfat_ownership_preflight_rename(vfs_node_t *target,
    u32 *out_entries, u32 *out_claimed, u32 destination)
{
    exfat_ownership_scan_t scan = {0};
    usize bitmap_bytes;
    int result = VFS_OK;

    if (!target || !target->super || !target->super->private_data ||
        !target->fs_data || (target->type != VFS_TYPE_FILE &&
                             target->type != VFS_TYPE_DIRECTORY))
        return VFS_ERR_INVALID_PARAM;
    scan.fs = (exfat_fs_t *)target->super->private_data;
    scan.rename_destination = destination;
    if (scan.fs->boot.fat_count != 1U || scan.fs->active_fat != 0U ||
        (scan.fs->boot.volume_flags & 0x000cU))
        return VFS_ERR_UNSUPPORTED;
    scan.target = target == target->super->root_node ? NULL :
                  (exfat_node_t *)target->fs_data;
    if (!scan.fs->version_confident ||
        (scan.target && !scan.target->version_valid)) return VFS_ERR_UNCERTAIN;
    if (scan.target && !scan.target->alive) return VFS_ERR_NOT_FOUND;
    if (!block_device_id_is_live(scan.fs->device_id)) return VFS_ERR_DEVICE_GONE;
    result = exfat_system_chain_check(scan.fs, scan.fs->bitmap_cluster,
                                      scan.fs->bitmap_length);
    if (result != VFS_OK) goto done;
    result = exfat_system_chain_check(scan.fs, scan.fs->upcase_cluster,
                                      scan.fs->upcase_length);
    if (result != VFS_OK) goto done;
    bitmap_bytes = ((usize)scan.fs->boot.cluster_count + 7U) / 8U;
    if (!bitmap_bytes || bitmap_bytes > EXFAT_SCAN_MAX_BITMAP_BYTES ||
        !scan.fs->cluster_bytes) return VFS_ERR_BUFFER_TOO_SMALL;
    scan.owned = (u8 *)kmalloc(bitmap_bytes);
    if (!scan.owned) { result = VFS_ERR_NO_MEM; goto done; }
    memset(scan.owned, 0, bitmap_bytes);
    /* The bitmap and upcase streams live in the heap and participate in
     * ownership like file data; their root entries are verified below. */
    result = exfat_scan_mapping(&scan, scan.fs->bitmap_cluster,
                                false,
                                scan.fs->bitmap_length, false, NULL);
    if (result != VFS_OK) goto done;
    result = exfat_scan_mapping(&scan, scan.fs->upcase_cluster,
                                false,
                                scan.fs->upcase_length, false, NULL);
    if (result != VFS_OK) goto done;
    result = exfat_scan_enqueue(&scan, (exfat_scan_directory_t){
        scan.fs->root_cluster, 0, false, true, false});
    if (result != VFS_OK) goto done;
    while (scan.head < scan.queued) {
        exfat_scan_directory_t job = scan.pending[scan.head++];
        result = exfat_scan_directory(&scan, &job);
        if (result != VFS_OK) break;
    }
    if (result == VFS_OK && (!scan.found_bitmap || !scan.found_upcase))
        result = VFS_ERR_BAD_FORMAT;
    if (result == VFS_OK && scan.target && !scan.found_target)
        result = VFS_ERR_NOT_FOUND;
    if (result == VFS_OK && out_entries) *out_entries = scan.entries;
    if (result == VFS_OK && out_claimed) *out_claimed = scan.claimed;
done:
    if (result == VFS_ERR_BAD_FORMAT) scan.fs->version_confident = false;
    kfree(scan.pending);
    kfree(scan.owned);
    return result;
}

static int exfat_ownership_preflight_locked_count(vfs_node_t *target,
    u32 *out_entries, u32 *out_claimed)
{
    return exfat_ownership_preflight_rename(target, out_entries, out_claimed, 0U);
}

static int exfat_ownership_preflight_locked(vfs_node_t *target)
{
    return exfat_ownership_preflight_locked_count(target, NULL, NULL);
}

static int exfat_find_entry_checked_view(exfat_fs_t *fs, u32 first, bool no_fat,
                                     u64 stream_length, const char *name,
                                     exfat_entry_info_t *out, bool *found,
                                     bool include_system, exfat_read_view_t *fat,
                                     exfat_stream_view_t *stream, bool unique)
{
    u64 offset = 0;
    exfat_entry_info_t item;
    u16 query[EXFAT_MAX_NAME_UNITS];
    u16 query_units;
    bool error = false;

    if (!fs || !name || !out || !found ||
        !exfat_utf8_to_utf16(name, query, &query_units, false))
        return VFS_ERR_INVALID_PARAM;
    *found = false;
    while (exfat_directory_next_view(fs, first, no_fat, stream_length,
                                &offset, &item,
                                include_system,
                                &error, fat, stream)) {
        if (query_units != item.name_length) continue;
        bool same = true;
        for (u16 i = 0; i < query_units; i++) {
            if (exfat_upcase_unit(fs, query[i]) !=
                exfat_upcase_unit(fs, item.name_units[i])) {
                same = false;
                break;
            }
        }
        if (same) {
            if (*found) {
                fs->version_confident = false;
                return VFS_ERR_BAD_FORMAT;
            }
            *out = item;
            *found = true;
            if (!unique) return VFS_OK;
        }
    }
    return error ? VFS_ERR_IO : VFS_OK;
}

static int exfat_find_entry_checked(exfat_fs_t *fs, u32 first, bool no_fat,
    u64 stream_length, const char *name, exfat_entry_info_t *out,
    bool *found, bool include_system)
{
    return exfat_find_entry_checked_view(fs, first, no_fat, stream_length,
                                         name, out, found,
                                         include_system, NULL, NULL, false);
}

/* Namespace collision scans are read-only under operation_lock. */
static int exfat_find_entry_locked_view(exfat_fs_t *fs, u32 first, bool no_fat,
    u64 stream_length, const char *name, exfat_entry_info_t *out, bool *found)
{
    exfat_read_view_t fat = {0};
    exfat_stream_view_t stream = {0};
    return exfat_find_entry_checked_view(fs, first, no_fat, stream_length,
                                         name, out, found,
                                         true, &fat, &stream, true);
}

static bool exfat_find_entry(exfat_fs_t *fs, u32 first, bool no_fat,
    u64 stream_length, const char *name, exfat_entry_info_t *out)
{
    bool found = false;
    return exfat_find_entry_checked(fs, first, no_fat, stream_length,
                                    name, out, &found,
                                    false) ==
               VFS_OK && found;
}

static exfat_node_t *exfat_find_node(exfat_fs_t *fs, u32 parent_cluster,
                                      u64 entry_offset)
{
    for (exfat_node_t *node = fs->nodes; node; node = node->next)
        if (node->alive && node->entry_count &&
            node->parent_cluster == parent_cluster &&
            node->entry_offset == entry_offset) return node;
    return NULL;
}

static void exfat_version_advance(exfat_node_t *node)
{
    if (!node || !node->version_valid) return;
    if (node->generation == ~(u64)0) node->version_valid = false;
    else node->generation++;
}

static vfs_node_t *exfat_attach_node(vfs_super_t *sb,
                                     const exfat_entry_info_t *entry,
                                     exfat_node_t *private_node,
                                     vfs_node_t *node)
{
    exfat_fs_t *fs = (exfat_fs_t *)sb->private_data;
    u32 permissions = EXFAT_VOLUME_PERMISSIONS;
    memset(private_node, 0, sizeof(*private_node));
    private_node->first_cluster = entry->first_cluster;
    private_node->no_fat_chain = (entry->stream_flags & EXFAT_STREAM_NO_FAT_CHAIN) != 0U;
    private_node->attributes = entry->attributes;
    private_node->data_length = entry->data_length;
    private_node->valid_data_length = entry->valid_data_length;
    private_node->entry_offset = entry->entry_offset;
    private_node->parent_cluster = entry->parent_cluster;
    private_node->parent_no_fat_chain = entry->parent_no_fat_chain;
    private_node->entry_count = entry->entry_count;
    strcpy(private_node->name, entry->name);
    memset(node, 0, sizeof(*node));
    node->inode = ++fs->next_inode;
    node->type = (entry->attributes & EXFAT_ATTR_DIRECTORY)
        ? VFS_TYPE_DIRECTORY : VFS_TYPE_FILE;
    node->size = entry->data_length;
    /* Preserve the portable exFAT read-only attribute as VFS write
     * protection.  Without this, an imported read-only file would appear
     * writable merely because the removable-volume policy is shared. */
    if (entry->attributes & EXFAT_ATTR_READ_ONLY)
        permissions &= ~(VFS_PERMISSION_OWNER_WRITE |
                         VFS_PERMISSION_OTHER_WRITE);
    vfs_node_set_security(node, VFS_UID_SYSTEM, permissions);
    node->ref_count = 1;
    node->super = sb;
    node->fs_data = private_node;
    node->ops = &exfat_node_ops;
    private_node->vfs_node = node;
    private_node->generation = 1;
    private_node->alive = true;
    private_node->version_valid = true;
    private_node->next = fs->nodes;
    fs->nodes = private_node;
    vfs_node_register(node);
    return node;
}

static vfs_node_t *exfat_make_node_context(vfs_super_t *sb,
                                   const exfat_entry_info_t *entry)
{
    exfat_fs_t *fs;
    exfat_node_t *existing;
    exfat_node_t *private_node;
    vfs_node_t *node;

    if (!sb || !entry || !sb->private_data) return NULL;
    fs = (exfat_fs_t *)sb->private_data;
    existing = exfat_find_node(fs, entry->parent_cluster,
                               entry->entry_offset);
    if (existing) {
        if (existing->first_cluster != entry->first_cluster ||
            existing->data_length != entry->data_length ||
            existing->valid_data_length != entry->valid_data_length ||
            existing->no_fat_chain !=
                !!(entry->stream_flags & EXFAT_STREAM_NO_FAT_CHAIN) ||
            existing->attributes != entry->attributes ||
            existing->entry_count != entry->entry_count ||
            strcmp(existing->name, entry->name) != 0) {
            existing->version_valid = false;
            return NULL;
        }
        return existing->vfs_node;
    }
    if (entry->first_cluster >= 2U) {
        for (exfat_node_t *other = fs->nodes; other; other = other->next) {
            if (other->alive && other->first_cluster == entry->first_cluster) {
                fs->version_confident = false;
                return NULL;
            }
        }
    }
    if (fs->next_inode == ~(u64)0) return NULL;
    private_node = (exfat_node_t *)kmalloc(sizeof(*private_node));
    node = (vfs_node_t *)kmalloc(sizeof(*node));
    if (!private_node || !node) {
        kfree(private_node);
        kfree(node);
        return NULL;
    }
    return exfat_attach_node(sb, entry, private_node, node);
}

/* Mounted callbacks are admitted with a superblock reference. Capture its
 * pointer once: forced detach can retarget parent->super during allocation or
 * I/O, but the admitted instance and its private state remain owned. */
static vfs_node_t *exfat_make_node(vfs_node_t *parent,
                                  const exfat_entry_info_t *entry)
{
    vfs_super_t *sb = parent ?
        __atomic_load_n(&parent->super, __ATOMIC_ACQUIRE) : NULL;
    return exfat_make_node_context(sb, entry);
}

static bool exfat_node_entry_read(exfat_node_t *node, exfat_fs_t *fs,
                                  u8 *set, u32 capacity)
{
    u32 bytes;

    if (!node || !fs || !set || !node->alive ||
        !node->version_valid || !fs->version_confident ||
        node->entry_count == 0U ||
        node->entry_count > EXFAT_MAX_SECONDARY + 1U) return false;
    bytes = (u32)node->entry_count * EXFAT_ENTRY_BYTES;
    if (bytes > capacity) return false;
    return exfat_dir_byte_read(fs, node->parent_cluster,
                               node->parent_no_fat_chain, node->entry_offset,
                               set, bytes);
}

static bool exfat_node_metadata_write(exfat_node_t *node, exfat_fs_t *fs)
{
    u8 set[(EXFAT_MAX_SECONDARY + 1U) * EXFAT_ENTRY_BYTES];
    u32 bytes;

    if (!node || !fs || !exfat_node_entry_read(node, fs, set, sizeof(set)))
        return false;
    bytes = (u32)node->entry_count * EXFAT_ENTRY_BYTES;
    exfat_put16(set + 4U, node->attributes);
    /* Preserve reserved flag bits and the separate reserved byte. */
    set[EXFAT_ENTRY_BYTES + 1U] =
        (set[EXFAT_ENTRY_BYTES + 1U] & ~EXFAT_STREAM_FLAGS) |
        EXFAT_STREAM_ALLOCATION_POSSIBLE |
        (node->no_fat_chain ? EXFAT_STREAM_NO_FAT_CHAIN : 0U);
    exfat_put64(set + EXFAT_ENTRY_BYTES + 8U, node->valid_data_length);
    exfat_put32(set + EXFAT_ENTRY_BYTES + 20U, node->first_cluster);
    exfat_put64(set + EXFAT_ENTRY_BYTES + 24U, node->data_length);
    exfat_put16(set + 2U, (u16)exfat_entry_checksum(set, node->entry_count));
    return exfat_dir_byte_write(fs, node->parent_cluster,
                                node->parent_no_fat_chain, node->entry_offset,
                                set, bytes);
}

static bool exfat_directory_length_refresh(exfat_fs_t *fs,
                                            exfat_node_t *directory,
                                            u64 previous_capacity)
{
    u64 capacity;
    u64 old_data;
    u64 old_valid;

    if (!fs || !directory ||
        !exfat_directory_capacity(fs, directory->first_cluster,
                                   directory->no_fat_chain,
                                   directory->data_length, &capacity))
        return false;
    if (capacity <= previous_capacity) return true;
    old_data = directory->data_length;
    old_valid = directory->valid_data_length;
    directory->data_length = capacity;
    directory->valid_data_length = capacity;
    /* The root directory has no file entry set of its own. */
    if (!directory->entry_count || exfat_node_metadata_write(directory, fs)) {
        if (directory->vfs_node)
            vfs_nodes_update_size(directory->vfs_node->super,
                                  directory->vfs_node->inode, capacity);
        return true;
    }
    directory->data_length = old_data;
    directory->valid_data_length = old_valid;
    return false;
}

static bool exfat_file_cluster(exfat_fs_t *fs, const exfat_node_t *node,
                               u64 index, u32 *out_cluster)
{
    if (!fs || !node || !node->first_cluster ||
        !exfat_chain_cluster(fs, node->first_cluster, node->no_fat_chain,
                             index, out_cluster)) return false;
    return true;
}

static bool exfat_file_read_bytes(exfat_fs_t *fs, const exfat_node_t *node,
                                  u64 offset, u64 length, void *buffer)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    u8 *out = (u8 *)buffer;

    if (!fs || !node || !buffer || !length || offset > node->data_length ||
        length > node->data_length - offset) return false;
    while (length) {
        u64 cluster_index = offset / fs->cluster_bytes;
        u64 within = offset % fs->cluster_bytes;
        u64 sector_index = within / EXFAT_SECTOR_BYTES;
        u32 sector_offset = (u32)(within % EXFAT_SECTOR_BYTES);
        u32 cluster;
        u64 lba;
        usize amount = EXFAT_SECTOR_BYTES - sector_offset;
        if ((u64)amount > length) amount = (usize)length;
        if (!exfat_file_cluster(fs, node, cluster_index, &cluster) ||
            (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
            !exfat_add_u64(lba, sector_index, &lba) ||
            !exfat_read(fs, lba, 1U, sector)) return false;
        memcpy(out, sector + sector_offset, amount);
        out += amount;
        offset += amount;
        length -= amount;
    }
    return true;
}

static u64 exfat_node_read(vfs_node_t *node, u64 offset, u64 size,
                           void *buffer)
{
    exfat_fs_t *fs;
    exfat_node_t *private_node;
    u64 available;
    u64 valid;

    if (!node || !node->super || !node->super->private_data ||
        node->type != VFS_TYPE_FILE || (size && !buffer)) return 0;
    fs = (exfat_fs_t *)node->super->private_data;
    private_node = (exfat_node_t *)node->fs_data;
    if (!fs->version_confident || !private_node || !private_node->alive ||
        !private_node->version_valid) return 0;
    if (!private_node || offset >= private_node->data_length || !size) return 0;
    available = private_node->data_length - offset;
    if (size > available) size = available;
    valid = private_node->valid_data_length > offset
        ? private_node->valid_data_length - offset : 0ULL;
    if (valid > size) valid = size;
    if (valid && !exfat_file_read_bytes(fs, private_node, offset, valid,
                                        buffer)) return 0;
    if (valid < size) {
        memset((u8 *)buffer + valid, 0, (usize)(size - valid));
        if (private_node->data_length > private_node->valid_data_length &&
            valid < size && private_node->valid_data_length > offset) {
            /* The region after ValidDataLength is intentionally zero-filled
             * for the caller; it need not have been read from media. */
        }
    }
    return size;
}

/* Validate the clusters mapped by one snapshot-sized stream without writing
 * media. This detects local loops, malformed links, and free bitmap bits,
 * but does not prove ownership uniqueness across the whole namespace. */
static int exfat_mapping_check(exfat_fs_t *fs, const exfat_node_t *node)
{
    u64 required;
    u64 limit;
    u32 current, tortoise;
    u32 power = 1U, span = 0U;

    if (!fs || !node || !fs->cluster_bytes) return VFS_ERR_BAD_FORMAT;
    required = node->data_length / fs->cluster_bytes +
               (node->data_length % fs->cluster_bytes != 0ULL);
    limit = MG_FILE_CONTENT_MAX_BYTES / fs->cluster_bytes;
    if (required > limit) return VFS_ERR_BUFFER_TOO_SMALL;
    if (!node->first_cluster)
        return required ? VFS_ERR_BAD_FORMAT : VFS_OK;
    if (node->first_cluster < 2U ||
        node->first_cluster > fs->boot.cluster_count + 1U)
        return VFS_ERR_BAD_FORMAT;
    if (node->no_fat_chain) {
        if (!required || required > fs->boot.cluster_count + 1ULL -
                                     node->first_cluster)
            return VFS_ERR_BAD_FORMAT;
        for (u64 index = 0; index < required; index++) {
            bool used;
            if (!exfat_bitmap_bit(fs, node->first_cluster + (u32)index,
                                  &used)) return VFS_ERR_IO;
            if (!used) return VFS_ERR_BAD_FORMAT;
        }
        return VFS_OK;
    }
    current = tortoise = node->first_cluster;
    for (u64 count = 0; count < limit; count++) {
        u32 next;
        bool used;
        if (current < 2U || current > fs->boot.cluster_count + 1U)
            return VFS_ERR_BAD_FORMAT;
        if (!exfat_bitmap_bit(fs, current, &used) ||
            !exfat_fat_get(fs, current, &next)) return VFS_ERR_IO;
        if (!used) return VFS_ERR_BAD_FORMAT;
        if (next >= EXFAT_CLUSTER_EOC_MIN)
            return count + 1U >= required ? VFS_OK : VFS_ERR_BAD_FORMAT;
        if (next < 2U || next > fs->boot.cluster_count + 1U)
            return VFS_ERR_BAD_FORMAT;
        if (power == span) {
            tortoise = current;
            power *= 2U;
            span = 0U;
        }
        current = next;
        span++;
        if (current == tortoise) return VFS_ERR_BAD_FORMAT;
    }
    return VFS_ERR_BUFFER_TOO_SMALL;
}

static int exfat_file_facts(vfs_node_t *node, vfs_file_facts_t *out)
{
    exfat_fs_t *fs;
    exfat_node_t *private_node;
    exfat_entry_info_t entry;
    u32 permissions;
    bool io_error;

    if (!node || !out || node->type != VFS_TYPE_FILE || !node->super ||
        !node->super->private_data) return VFS_ERR_UNSUPPORTED;
    fs = (exfat_fs_t *)node->super->private_data;
    private_node = (exfat_node_t *)node->fs_data;
    if (!fs->version_confident || !private_node ||
        !private_node->version_valid) return VFS_ERR_UNCERTAIN;
    if (!private_node->alive) return VFS_ERR_NOT_FOUND;
    if (!exfat_entry_set_read_checked(fs, private_node->parent_cluster,
                                      private_node->parent_no_fat_chain,
                                      private_node->entry_offset, &entry,
                                      &io_error)) {
        if (io_error) return VFS_ERR_IO;
        private_node->version_valid = false;
        fs->version_confident = false;
        return VFS_ERR_BAD_FORMAT;
    }
    if (entry.first_cluster != private_node->first_cluster ||
        entry.data_length != private_node->data_length ||
        entry.valid_data_length != private_node->valid_data_length ||
        entry.attributes != private_node->attributes ||
        entry.entry_count != private_node->entry_count ||
        strcmp(entry.name, private_node->name) != 0 ||
        node->size != entry.data_length) {
        private_node->version_valid = false;
        return VFS_ERR_UNCERTAIN;
    }
    int mapping_result = exfat_mapping_check(fs, private_node);
    if (mapping_result != VFS_OK) {
        if (mapping_result == VFS_ERR_BAD_FORMAT) {
            private_node->version_valid = false;
            fs->version_confident = false;
        }
        return mapping_result;
    }
    permissions = node->permissions;
    if (entry.attributes & EXFAT_ATTR_READ_ONLY)
        permissions &= ~(VFS_PERMISSION_OWNER_WRITE |
                         VFS_PERMISSION_OTHER_WRITE);
    *out = (vfs_file_facts_t){
        .record_id = node->inode,
        .generation = private_node->generation,
        .size = entry.data_length,
        .owner_uid = node->owner_uid,
        .permissions = permissions,
    };
    return VFS_OK;
}

static int exfat_snapshot_stream(vfs_node_t *node, usize capacity,
                                  vfs_snapshot_sink_t sink, void *context,
                                  mg_file_lines_state_t *state)
{
    vfs_file_facts_t facts;
    u8 chunk[4096];
    int result;

    if (!sink || !state || capacity > MG_FILE_CONTENT_MAX_BYTES)
        return VFS_ERR_INVALID_PARAM;
    result = exfat_file_facts(node, &facts);
    if (result != VFS_OK) return result;
    if (facts.size > capacity) return VFS_ERR_BUFFER_TOO_SMALL;
    for (u64 offset = 0; offset < facts.size;) {
        usize count = facts.size - offset > sizeof(chunk)
            ? sizeof(chunk) : (usize)(facts.size - offset);
        if (exfat_node_read(node, offset, count, chunk) != count)
            return VFS_ERR_IO;
        result = sink(context, offset, chunk, count);
        if (result != VFS_OK) return result;
        offset += count;
    }
    *state = (mg_file_lines_state_t){facts.record_id, facts.generation,
                                      facts.size, 0};
    return VFS_OK;
}

